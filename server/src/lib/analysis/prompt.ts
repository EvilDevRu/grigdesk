// Промпт триаж-разведчика. Задача агента — оценить сложность/риски по коду,
// НЕ составляя план реализации (план делает конвейер на живом master при взятии задачи).
// Результат агент пишет сам в два файла каталога анализа — раннер только валидирует.

import { DISCUSSION_SECTION_TITLE } from '../telegram/discussion.ts';
import type { TriageProfile } from './profile.ts';

const CAP_DESC = 8000;    // описание тикета, символов
const CAP_COMMENT = 1500; // один комментарий
const MAX_COMMENTS = 15;  // последних комментариев

// Уточнения человека — накопительный файл с base64-маркерами ответов (analyzer.ts):
// один ответ вместе со своим вопросом весит 1–2 тыс. символов, и потолок в 6000 отрезал
// хвост уже на пятом-шестом. Тот же предел держит вклейку уточнений в тикет конвейера
// (modules/factory): триаж и конвейер обязаны видеть один и тот же объём.
export const CAP_CLARIFICATIONS = 30_000;

export interface TriageComment {
  author?: string;
  time?: string;
  text?: string;
}

// Закрытый вопрос прошлого захода: что спрашивали и что ответили. Ответ приходит
// уже собранной строкой — промпту важен смысл, а не поля записи.
export interface TriageAnsweredQuestion {
  question: string;
  answer: string;
  actor: 'human' | 'cockpit-arbiter';
}

export interface TriageRouteChoice {
  kinds?: string[];
  routes?: { id?: string; title?: string }[];
}

export interface TriagePromptInput {
  task: string | number;
  title: string;
  description: string;
  comments?: TriageComment[];
  clarifications?: string;
  answered?: TriageAnsweredQuestion[];
  discussion?: string;
  profile: TriageProfile;
  routeChoice?: TriageRouteChoice | null;
  jsonPath: string;
  notePath: string;
}

/**
 * Собирает промпт разведчика. Роды работ и каталог маршрутов приходят из профиля:
 * пустой список означает профиль без карты — тогда спрашиваем исторический enum,
 * иначе триаж назовёт маршрут, которого движок не примет.
 */
export function buildTriagePrompt({
  task, title, description, comments, clarifications, answered, discussion, profile,
  routeChoice, jsonPath, notePath,
}: TriagePromptInput): string {
  const comm = (comments || [])
    .slice(-MAX_COMMENTS)
    .map((c) => `- ${c.author}${c.time ? ` (${c.time})` : ''}: ${String(c.text || '').slice(0, CAP_COMMENT)}`)
    .join('\n');

  const repoList = (profile.repos || []).map((r) => `${r.key}: ${r.dir}`).join('\n');

  // Род работы модель выбирает из объявленных профилем; глубину она не выбирает вовсе.
  const kinds = (routeChoice?.kinds || []).filter(Boolean);
  const routes = (routeChoice?.routes || []).filter((route) => route?.id);
  const kindList = kinds.length ? kinds.join(' | ') : 'feature | debug | trivial';
  const routeCatalog = routes.length
    ? `\nМаршруты этого профиля (их выберет политика, тебе выбирать не нужно):\n${
      routes.map((route) => `- ${route.id}${route.title ? ` — ${route.title}` : ''}`).join('\n')}\n`
    : '';

  // Закрытые вопросы показываем ПАРАМИ. Прошлый заход видел только реплики ответов без
  // самих вопросов — и штатно спрашивал то же самое снова, обнуляя работу человека.
  const closed = (answered || []).filter((item) => item?.question && item?.answer);
  const closedBlock = closed.length
    ? `\n[Закрытые вопросы — на них уже ответили, повторно НЕ спрашивай]\n${
      closed.map((item, index) => `${index + 1}. Вопрос: ${item.question}\n   Ответ (${
        item.actor === 'human' ? 'человек' : 'арбитр, по коду'}): ${item.answer}`).join('\n')
    }\nЭти ответы — часть постановки: считай их фактом, учитывай в оценке и НЕ выноси эти вопросы в questions[] ни в какой формулировке. Если они снимали неопределённость — подними confidence и не ставь needs_clarification только из-за них.`
    : '';

  return `Ты — триаж-разведчик задач трекера. Цель: быстро и честно оценить сложность, риски и объём задачи ПО КОДУ. План реализации НЕ составлять — его позже сделает конвейер по свежему коду.

РЕЖИМ: только чтение. Работаешь в ОСНОВНЫХ репозиториях проекта (стенда/песочницы нет), поэтому никаких docker/artisan/npm/тестов. Ищи и читай файлы доступными файловыми инструментами, историю смотри только через структурный repo_history (log/show). Код не менять.

[Контекст проекта]
${profile.ctx || '(профиль проекта недоступен — оценивай по коду, confidence не выше medium)'}

Репозитории (префиксы для путей в files[]):
${repoList || '(не заданы)'}
${routeCatalog}
[Задача #${task}]
Название: ${title}
Описание:
${String(description || '(пусто)').slice(0, CAP_DESC)}
${comm ? `\nКомментарии (последние, старые → новые):\n${comm}` : ''}
${clarifications ? `\n[Уточнения человека — внутренние, ответы на вопросы прошлого триажа; приоритетнее описания]\n${String(clarifications).slice(0, CAP_CLARIFICATIONS)}` : ''}${closedBlock}
${`${comm}${clarifications || ''}`.includes('[приложено фото:') ? '\nПометки «[приложено фото: /путь]» — скриншоты от человека, ОБЯЗАТЕЛЬНО открой каждый инструментом Read и учти содержимое в оценке.' : ''}
${discussion ? `\n${DISCUSSION_SECTION_TITLE}\n${discussion}\nЭто уже раскрытая переписка — доступ к ней просить не нужно. Строки «Ссылка не раскрыта» — то, что осталось недоступным: их и учитывай в confidence.\n` : ''}
[Что сделать]
1. Разведай код: где живёт затронутый функционал, какие файлы/подсистемы придётся трогать (смотри ВСЕ репозитории из списка выше).
2. Оцени задачу по рубрике ниже.
3. Запиши РОВНО два файла (единственные файлы, которые ты пишешь):
   - ${jsonPath} — строго по схеме ниже, валидный JSON без комментариев;
   - ${notePath} — разведнота (markdown).

[Рубрика]
complexity (1–5): 1 = точечная правка одного файла/компонента; 2 = несколько файлов в одном слое; 3 = сквозная фича через слои (API+логика+UI) по готовым паттернам; 4 = новая подсистема, изменение схемы данных или нетривиальный алгоритм; 5 = сквозная фича + изменение схемы/очередей/агрегатов, много точек интеграции.
risk (1–5): цена ошибки и необратимость последствий, НЕ трудоёмкость. 1 = косметика, откат тривиален; 3 = можно сломать заметный пользователю сценарий; 5 = порча/потеря данных, деньги, безопасность.${profile.markers ? `\nПроектные маркеры риска (каждый найденный поднимает оценку):\n${profile.markers}` : ''}
diff_size: S (<50 строк), M (50–300), L (300–1000), XL (>1000) — прогноз итогового диффа.
route_kind (род работы, НЕ глубина проверки): ${kindList}. feature — нужно новое или изменённое поведение; debug — есть наблюдаемый дефект, причину надо сначала доказать; perf — предмет задачи скорость; hunt — просят найти дефекты в области, а не чинить конкретный.
ГЛУБИНУ маршрута (полный / средний / лёгкий) выбираешь НЕ ты: её считает политика по твоим complexity, risk, diff_size, confidence и по наличию открытых вопросов. Поэтому оценки должны быть честными в обе стороны: завышенная сложность отправит мелкую правку по полному кругу с планом и воротами, заниженный риск — наоборот. Про сам маршрут в summary писать не нужно.
confidence: high | medium | low. Если тикет мутный, цель непонятна или есть недоступные ссылки (нераскрытые t.me/…, скрины без текста) — ставь low, заполняй questions[] и needs_clarification=true. НЕ фантазируй охват: честное «нужно уточнение» ценнее выдуманной оценки.
questions[] — только то, что ОСТАЛОСЬ открытым. Вопрос из блока закрытых, переформулированный другими словами, — тот же вопрос: его задавать нельзя.

[Схема ${jsonPath}]
{
  "task": ${task},
  "project": "<префикс из названия задачи до первого |, как есть>",
  "route_kind": "<один род из списка выше>",
  "complexity": 1-5,
  "risk": 1-5,
  "diff_size": "S|M|L|XL",
  "areas": ["BE","FE","DB-migration","user_db-migration","ClickHouse","queues","billing","security","infra"],
  "files": ["<префикс>:<путь от корня репо>", "..."],
  "risk_markers": ["<найденные проектные маркеры риска, своими словами>"],
  "unknowns": ["<что осталось непонятным про код/поведение — для планировщика, можно технически>"],
  "questions": [{
    "text": "<один вопрос постановщику>",
    "options": [{"label": "<вариант>", "description": "<необязательное пояснение>"}],
    "recommendation": {"option": "<рекомендуемый вариант>", "reason": "<почему>"}
  }],
  "needs_clarification": false,
  "confidence": "high|medium|low",
  "scope": {
    "do": ["<по одному пункту на КАЖДЫЙ пункт постановки: что изменится для пользователя>", "..."],
    "skip": ["<пункт постановки, который НЕ делаем, и почему: ответ человека / вне задачи>", "..."]
  },
  "summary": "<1–2 предложения: что делать и почему такая оценка>"
}
areas[] — только реально затронутые значения из списка. files[] — 5–20 самых важных путей, не листинг всего подряд.
scope — объём задачи, как его увидит человек на запуске и как его получит конвейер критериями приёмки. do[] — языком результата («в окне X показано Y», «кнопка Z запускает …»), не техническими шагами; каждый пункт постановки («Что не так: 1…N», «Итог», «нужно сделать») обязан попасть либо в do[], либо в skip[] с причиной. «Уже реализовано в коде» — НЕ причина для skip[]: если постановка называет существующий экран, окно или текст недостаточным, человек смотрел именно на него — это пункт do[]. В skip[] только то, что закрыто ответом человека или явно не относится к задаче.
Разница аудиторий: unknowns[] читает планировщик — можно технически, с путями и терминами. questions[] читает владелец продукта, не разработчик: пиши на человеческом языке, без путей файлов, имён классов, SQL и жаргона. Варианты клади отдельными объектами options, а совет — отдельно в recommendation; не прячь их внутри text.

[Структура разведноты ${notePath}]
# t${task}: <название задачи>
## Как это работает сейчас — факты с путями к файлам
## Что придётся трогать — по репозиториям
## Риски — что и почему может пойти не так
## Вопросы/неизвестное
Разведнота — это карта для будущего планировщика: факты и пути, без планов и без пересказа тикета.

В конце ответа выведи одну строку-резюме с оценками (complexity/risk/size/confidence).`;
}
