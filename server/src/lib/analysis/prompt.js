// Промпт триаж-разведчика. Задача агента — оценить сложность/риски по коду,
// НЕ составляя план реализации (план делает конвейер на живом master при взятии задачи).
// Результат агент пишет сам в два файла каталога анализа — раннер только валидирует.

import { DISCUSSION_SECTION_TITLE } from '../telegram/discussion.js';

const CAP_DESC = 8000;    // описание тикета, символов
const CAP_COMMENT = 1500; // один комментарий
const MAX_COMMENTS = 15;  // последних комментариев

/**
 * @param {object} p
 * @param {string|number} p.task номер задачи
 * @param {string} p.title заголовок задачи (с префиксом проекта)
 * @param {string} p.description текст описания (уже без HTML)
 * @param {Array<{author:string,time:string,text:string}>} p.comments несистемные комментарии
 * @param {string} [p.discussion] переписка по телеграм-ссылкам из задачи (уже с лимитами)
 * @param {{ctx:string, markers:string, repos:Array<{key:string,dir:string}>}} p.profile
 * @param {string} p.jsonPath куда писать analysis.json
 * @param {string} p.notePath куда писать разведноту
 */
export function buildTriagePrompt({ task, title, description, comments, clarifications, discussion, profile, jsonPath, notePath }) {
  const comm = (comments || [])
    .slice(-MAX_COMMENTS)
    .map((c) => `- ${c.author}${c.time ? ` (${c.time})` : ''}: ${String(c.text || '').slice(0, CAP_COMMENT)}`)
    .join('\n');

  const repoList = (profile.repos || []).map((r) => `${r.key}: ${r.dir}`).join('\n');

  return `Ты — триаж-разведчик задач трекера. Цель: быстро и честно оценить сложность, риски и объём задачи ПО КОДУ. План реализации НЕ составлять — его позже сделает конвейер по свежему коду.

РЕЖИМ: только чтение. Работаешь в ОСНОВНЫХ репозиториях проекта (стенда/песочницы нет), поэтому никаких docker/artisan/npm/тестов. Ищи и читай файлы доступными файловыми инструментами, историю смотри только через структурный repo_history (log/show). Код не менять.

[Контекст проекта]
${profile.ctx || '(профиль проекта недоступен — оценивай по коду, confidence не выше medium)'}

Репозитории (префиксы для путей в files[]):
${repoList || '(не заданы)'}

[Задача #${task}]
Название: ${title}
Описание:
${String(description || '(пусто)').slice(0, CAP_DESC)}
${comm ? `\nКомментарии (последние, старые → новые):\n${comm}` : ''}
${clarifications ? `\n[Уточнения человека — внутренние, ответы на вопросы прошлого триажа; приоритетнее описания]\n${String(clarifications).slice(0, 6000)}` : ''}
${`${comm}${clarifications || ''}`.includes('[приложено фото:') ? '\nПометки «[приложено фото: /путь]» — скриншоты от человека, ОБЯЗАТЕЛЬНО открой каждый инструментом Read и учти содержимое в оценке.' : ''}
${discussion ? `\n${DISCUSSION_SECTION_TITLE}\n${discussion}\nЭто уже раскрытая переписка — доступ к ней просить не нужно. Строки «Ссылка не раскрыта» — то, что осталось недоступным: их и учитывай в confidence.\n` : ''}
[Что сделать]
1. Разведай код: где живёт затронутый функционал, какие файлы/подсистемы придётся трогать (смотри ВСЕ репозитории из списка выше).
2. Оцени задачу по рубрике ниже.
3. Запиши РОВНО два файла (единственные файлы, которые ты пишешь):
   - ${jsonPath} — строго по схеме ниже, валидный JSON без комментариев;
   - ${notePath} — разведнота (markdown).

[Рубрика]
complexity (1–5): 1 = точечная правка одного файла/компонента; 2 = несколько файлов в одном слое; 3 = сквозная фича через слои (API+логика+UI) по готовым паттернам; 4 = новая подсистема, изменение схемы данных или нетривиальный алгоритм; 5 = сквозная фича + изменение схемы/очередей/агрегатов, много точек интеграции.
risk (1–5): цена ошибки и необратимость последствий, НЕ трудоёмкость. 1 = косметика, откат тривиален; 3 = можно сломать заметный пользователю сценарий; 5 = порча/потеря данных, деньги, безопасность.${profile.markers ? `\nПроектные маркеры риска (каждый найденный поднимает оценку):\n${profile.markers}` : ''}
diff_size: S (<50 строк), M (50–300), L (300–1000), XL (>1000) — прогноз итогового диффа.
route_guess: feature (новое поведение) | debug (сломано существующее, надо сначала воспроизвести) | trivial (мелочь без плана).
confidence: high | medium | low. Если тикет мутный, цель непонятна или есть недоступные ссылки (нераскрытые t.me/…, скрины без текста) — ставь low, заполняй questions[] и needs_clarification=true. НЕ фантазируй охват: честное «нужно уточнение» ценнее выдуманной оценки.

[Схема ${jsonPath}]
{
  "task": ${task},
  "project": "<префикс из названия задачи до первого |, как есть>",
  "route_guess": "feature|debug|trivial",
  "complexity": 1-5,
  "risk": 1-5,
  "diff_size": "S|M|L|XL",
  "areas": ["BE","FE","DB-migration","user_db-migration","ClickHouse","queues","billing","security","infra"],
  "files": ["<префикс>:<путь от корня репо>", "..."],
  "risk_markers": ["<найденные проектные маркеры риска, своими словами>"],
  "unknowns": ["<что осталось непонятным про код/поведение — для планировщика, можно технически>"],
  "questions": [{
    "text": "<один вопрос постановщику>",
    "options": [{"label": "<вариант>", "description": "<необязательное пояснение>"}],
    "recommendation": {"option": "<рекомендуемый вариант>", "reason": "<почему>"}
  }],
  "needs_clarification": false,
  "confidence": "high|medium|low",
  "summary": "<1–2 предложения: что делать и почему такая оценка>"
}
areas[] — только реально затронутые значения из списка. files[] — 5–20 самых важных путей, не листинг всего подряд.
Разница аудиторий: unknowns[] читает планировщик — можно технически, с путями и терминами. questions[] читает владелец продукта, не разработчик: пиши на человеческом языке, без путей файлов, имён классов, SQL и жаргона. Варианты клади отдельными объектами options, а совет — отдельно в recommendation; не прячь их внутри text.

[Структура разведноты ${notePath}]
# t${task}: <название задачи>
## Как это работает сейчас — факты с путями к файлам
## Что придётся трогать — по репозиториям
## Риски — что и почему может пойти не так
## Вопросы/неизвестное
Разведнота — это карта для будущего планировщика: факты и пути, без планов и без пересказа тикета.

В конце ответа выведи одну строку-резюме с оценками (complexity/risk/size/confidence).`;
}
