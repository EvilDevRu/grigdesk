// Почему конвейер стоит.
//
// Движок умеет останавливаться САМ: три попытки этапа без результата, два возврата
// в сборку без толку, упавший стенд, нехватка прав на запись статуса. В каждом из
// этих случаев он ставит STALLED_HUMAN=1 и пишет причину строкой в
// logs/tNNNN.stages.log — и на этом всё. Кокпит флаг читал (`stalledHuman` в сводке
// задачи), но не показывал нигде: единственным индикатором оставалось «○ стоит» по
// живости демона, одинаковое и для доделанной задачи, и для той, что ждёт человека.
//
// REPRO может не воспроизвести баг, движок корректно встанет и позовёт человека,
// но без отдельного признака человек об этом не узнает. Этот модуль достаёт причину из журнала и
// формулирует её так, чтобы по ней было понятно, что делать.
import { parseStagesLog } from './stagesParse.ts';

// Событие журнала в том минимуме, который нужен разбору: когда и что напечатал движок.
export interface StallEvent {
  ts: string;
  event: string;
}

// Что правило вычитало из строки: узел, машинный вид остановки и тексты человеку.
interface HaltMatch {
  stage: string | null;
  stop?: string;
  title: string;
  hint: string;
}

// Правило разбора: регулярка формулировки движка и сборка причины по её группам.
interface HaltRule {
  re: RegExp;
  build: (m: RegExpExecArray) => HaltMatch;
}

// Найденная причина: разобранное правило плюс сама строка журнала и её время.
type StallCause = HaltMatch & { detail: string | null; since: string | null };

// Вход классификатора: реестр задачи, журнал (готовым списком или текстом) и живость демона.
export interface StallInput {
  registry?: Record<string, string | undefined>;
  timeline?: StallEvent[];
  logText?: string;
  daemonAlive: boolean;
}

// Ответ классификатора. `kind` отделяет объявленную остановку от молчаливого обрыва.
export interface StallInfo extends StallCause {
  kind: 'human' | 'crashed';
  fails: number | null;
  comment: string | null;
}

// Формулировки движка (lib/core.sh) → человеческая причина и что с ней делать.
// Порядок не важен: ищем с конца журнала, берём первое совпадение.
const HALT_RULES: readonly HaltRule[] = [
  // Причина после тире — та самая, что движок вычислил в no_progress_reason
  // (повтор набора / осцилляция / расширение области). Раньше она оседала только
  // в immutable ledger, и человек читал generic-подсказку про «повтор ИЛИ
  // осцилляцию» в момент, когда движок точно знал, что именно произошло.
  {
    re: /^([A-Z][A-Z0-9_]*): маршрут остановлен: no-progress(?: — (.+))?$/,
    build: (m) => ({
      stage: m[1] ?? null,
      // Машинный вид остановки. Заголовок и подсказка — человеку, а решение «можно ли
      // отдать это арбитру» обязано приниматься по типу, а не по разбору русского текста.
      stop: 'no-progress',
      title: m[2]
        ? `${m[1]}: ${m[2]}`
        : `${m[1]}: исправления не меняют набор замечаний`,
      hint: 'блокирующие замечания пережили ремонт — либо реши их вручную, либо верни узел с указанием, что считать отложенным',
    }),
  },
  {
    re: /^([A-Z][A-Z0-9_]*): маршрут остановлен: rewind-limit(?: — (.+))?$/,
    build: (m) => ({
      stage: m[1] ?? null,
      stop: 'rewind-limit',
      title: m[2]
        ? `${m[1]}: ${m[2]}`
        : `${m[1]}: исчерпан защитный лимит возвратов`,
      hint: 'старый этап не передал typed findings — посмотри комментарий и выбери точку возврата вручную',
    }),
  },
  // Узел сам вернул решение человеку: маршрут объявил `stop: human` в `on`/`onFailure`
  // по классу провала, который назвал агент (`verdict.owner`). Это САМАЯ частая
  // объявленная остановка — 2785 переходов против 184 `done` по всем опубликованным
  // каталогам, — и до 28.08.2026 её не ловило ни одно правило: движок писал её голой
  // строкой без узла. Человек видел «причина не нашлась в журнале» ровно там, где узел
  // и его развёрнутое замечание уже лежали в журнале попытки.
  //
  // Арбитру такая остановка не отдаётся намеренно: `ARBITRABLE_STOPS` держит только
  // `no-progress`, а класс `human` означает, что решение не выводится из вердиктов дуги.
  // Поле `stop` заполняется всё равно — вид остановки нужен и тому, кто её показывает.
  {
    re: /^([A-Z][A-Z0-9_]*): маршрут остановлен: human$/,
    build: (m) => ({
      stage: m[1] ?? null,
      stop: 'human',
      title: `${m[1]}: узел вернул решение человеку`,
      hint: 'агент отдал развилку человеку — открой узел и прочитай его замечание: там сказано, чего не хватает',
    }),
  },
  // Тот же случай в журналах, написанных до 28.08.2026: узла в строке нет, и взять его
  // неоткуда. Тип остановки при этом известен точно, а он и есть главное: «ждёт
  // человека» вместо «причина не нашлась».
  {
    re: /^маршрут остановлен: human$/,
    build: () => ({
      // Узел назвать нечем, но поле контракта пустым быть обязано, а не отсутствовать:
      // его читают и DTO графа, и подстановка `<STAGE>_FAILS`/`_COMMENT` ниже.
      stage: null,
      stop: 'human',
      title: 'маршрут вернул решение человеку',
      hint: 'узел отдал развилку человеку — какой именно, journal этой записи не называет: смотри последний исполненный узел на схеме',
    }),
  },
  {
    re: /^([A-Z_]+): (\d+) возврата не помогли/,
    build: (m) => ({
      stage: m[1] ?? null,
      title: `${m[1]}: ${m[2]} возврата не помогли`,
      hint: 'этап падает раз за разом — посмотри его отчёт: чинить, менять план или вести руками',
    }),
  },
  {
    re: /^([A-Z_]+): 3 попытки без результата/,
    build: (m) => ({
      stage: m[1] ?? null,
      title: `${m[1]}: агент трижды не отчитался о результате`,
      hint: 'этап не выставил статус — обычно упирается в бюджет времени, права или недоступный инструмент',
    }),
  },
  {
    re: /^([A-Z_]+): агенту не дали записать результат/,
    build: (m) => ({
      stage: m[1] ?? null,
      title: `${m[1]}: агенту не хватило прав записать статус`,
      hint: 'повтор бесполезен — нужны права на запись в реестр (песочница/settings этапа)',
    }),
  },
  {
    re: /^sandbox_up упал/,
    build: () => ({
      stage: 'SANDBOX',
      title: 'стенд не поднялся',
      hint: 'смотри хвост logs/tNNNN.orch.log — чаще всего занятый порт или недоснесённая песочница',
    }),
  },
  {
    // Первая форма — текущая нейтральная; вторая нужна только для чтения
    // архивных журналов, созданных до operational cutover.
    re: /^(?:(?:v2: )?свежая v2-песочница|(?:v2: )?среда профиля) не готова \(код (\d+)\)/,
    build: (m) => ({
      stage: 'SANDBOX',
      title: `среда профиля не готова (код ${m[1]})`,
      hint: m[1] === '75'
        ? 'проверь exact checkout/ветку; для isolated-режима отдельно проверь остатки песочницы, shared-ресурсы не удаляй'
        : 'смотри хвост logs/tNNNN.orch.log; shared-стенд должен восстановить его внешний владелец',
    }),
  },
  {
    re: /^([A-Z_]+): агент убит по таймауту/,
    build: (m) => ({
      stage: m[1] ?? null,
      title: `${m[1]}: агент убит по таймауту`,
      hint: 'работа этапа потеряна целиком — поднимай лимит времени этапа, а не правь промпт',
    }),
  },
];

// Журнал задачи ведётся МЕСЯЦАМИ и переживает любое число прогонов, поэтому причину
// остановки нельзя искать по всей его длине: найдётся первая попавшаяся с конца, даже
// если после неё маршрут прошёл десяток узлов. Живые случаи 28.08.2026: задача ждала у
// ворот приёмки, а карточка показывала «среда профиля не готова (код 73)» из строки №5
// журнала, написанной за 25 дней до того; соседняя ждала там же, а показывала снятый
// три часа назад `no-progress` — и по этому же полю гейтится арбитр, то есть автомат
// пошёл бы двигать курсор назад по уже принятой работе.
//
// Граница окна — последнее событие, доказывающее, что маршрут ПОЕХАЛ дальше. Всё, что
// раньше него, принадлежит прошлым заходам и текущей причиной быть не может. Событий
// продвижения три, и все они печатаются самим движком:
//   - заход в узел (`узел X: подготовка к исполнению`);
//   - зафиксированное решение ворот (`gate X=... зафиксирован`);
//   - возврат курсора — человеком (`курсор возвращён человеком на узел X`) либо
//     движком при восстановлении инструментации (`восстановление: ... курсор возвращён`).
// Нет ни одного такого события — окном остаётся весь журнал: сузить его нечем, а прежнее
// поведение здесь безопасно (единственный прогон, единственная причина).
const PROGRESS_RE = /^(?:узел [a-z0-9_]+: подготовка к исполнению|gate [a-z0-9_]+=[a-z-]+ зафиксирован|курсор возвращён человеком на узел |восстановление: .*курсор возвращён)/;

// Последняя строка нормально доведённого прогона. Формулировок две: движок v2 пишет
// «маршрут завершён; SHIP и RETRO подтверждены» (`bin/factory`), «конвейер завершён»
// осталось только в архивных журналах v1. Пока здесь стояла одна v1-форма, КАЖДЫЙ
// доведённый до конца маршрут показывался как «✖ оборвалась»: терминальная попытка,
// RESULT=completed и совет «запусти заново» одновременно.
//
// Точка с запятой обязательна: у движка есть близкая строка «маршрут завершён, но
// shared lease не освобождён (код N)». Она под правило НЕ подпадает намеренно —
// занятая лиза блокирует следующий прогон, и человек должен её увидеть.
const FINISHED = /маршрут завершён;|конвейер завершён/;

/**
 * Классифицирует остановку конвейера.
 * null — конвейер не стоит: идёт, доделан или ждёт решения на воротах.
 */
export function detectStall(
  { registry = {}, timeline, logText, daemonAlive }: StallInput,
): StallInfo | null {
  const events = timeline || (logText ? parseStagesLog(logText) : []);
  const stalled = registry.STALLED_HUMAN === '1';

  // Демон жив — конвейер работает или стоит на воротах (у ворот своя кнопка, это не затык).
  if (daemonAlive && !stalled) return null;

  // Ниже какого индекса смотреть бесполезно: там прошлые заходы этой же задачи.
  let windowStart = 0;
  for (let i = events.length - 1; i >= 0; i -= 1) {
    const entry = events[i];

    if (entry && PROGRESS_RE.test(entry.event.replace(/^route:\s+/, ''))) {
      windowStart = i + 1;
      break;
    }
  }

  let found: StallCause | null = null;
  for (let i = events.length - 1; i >= windowStart && !found; i -= 1) {
    const entry = events[i];

    if (!entry) continue;
    // Оркестратор v2 префиксует КАЖДУЮ свою строку журнала словом `route: `
    // (`v2_log` в engine/bin/factory). Правила ниже писались по форме v1 и якорятся
    // на начало строки, поэтому с переходом на v2 не совпадало ни одно из них: любой
    // затык показывался общим «причина не нашлась в журнале», хотя точная строка в
    // журнале была. Снимаем префикс здесь, в одном месте, а не дублируем его в
    // восьми регулярных выражениях.
    const event = entry.event.replace(/^route:\s+/, '');
    for (const rule of HALT_RULES) {
      const m = rule.re.exec(event);
      if (!m) continue;
      found = { ...rule.build(m), detail: event, since: entry.ts };
      break;
    }
  }

  if (stalled) {
    // Пауза у ворот — НЕ затык: «у ворот своя кнопка» (жёлтая плашка «ждёт тебя»
    // + чип). Единый launcher на гейте ставит STALLED_HUMAN=1 и выходит — без этой
    // ветки штатная пауза красила узел в stall, убивала waitingReason и рисовала
    // красное «причина не нашлась в журнале».
    const gate = Object.keys(registry)
      .find((k) => /^GATE_[A-Z_]+$/.test(k) && registry[k] === 'waiting');
    if (gate && !found) return null;
    const base: StallCause = found || {
      stage: null,
      title: 'конвейер остановлен и ждёт человека',
      hint: 'причина не нашлась в журнале — смотри logs/tNNNN.stages.log',
      detail: null,
      since: events.at(-1)?.ts ?? null,
    };
    const fails = base.stage && registry[`${base.stage}_FAILS`] ? Number(registry[`${base.stage}_FAILS`]) : null;
    const comment = base.stage ? (registry[`${base.stage}_COMMENT`] || null) : null;
    return { kind: 'human', fails, comment, ...base };
  }

  // Флага нет, а демона тоже нет: конвейер оборвался молча — упал, был убит или
  // зачищен вместе с cgroup. Отличаем от нормального финала по последней строке.
  const last = events.at(-1) ?? null;
  if (!last || FINISHED.test(last.event)) return null;
  return {
    kind: 'crashed',
    stage: found?.stage || null,
    title: found?.title || 'конвейер оборвался, не дойдя до конца',
    detail: found?.detail || last.event,
    since: found?.since || last.ts,
    hint: 'демона нет, а конвейер не закрыт — запусти заново (resume продолжит с этого места)',
    fails: null,
    comment: null,
  };
}
