// Почему конвейер стоит.
//
// Движок умеет останавливаться САМ: три попытки этапа без результата, два возврата
// в сборку без толку, упавший стенд, нехватка прав на запись статуса. В каждом из
// этих случаев он ставит STALLED_HUMAN=1 и пишет причину строкой в
// logs/tNNNN.stages.log — и на этом всё. Кокпит флаг читал (`stalledHuman` в сводке
// задачи), но не показывал нигде: единственным индикатором оставалось «○ стоит» по
// живости демона, одинаковое и для доделанной задачи, и для той, что ждёт человека.
//
// REPRO может не воспроизвести баг, движок корректно встанет и позовёт человека,
// но без отдельного признака человек об этом не узнает. Этот модуль достаёт причину из журнала и
// формулирует её так, чтобы по ней было понятно, что делать.
import { parseStagesLog } from './stagesParse.ts';

// Событие журнала в том минимуме, который нужен разбору: когда и что напечатал движок.
export interface StallEvent {
  ts: string;
  event: string;
}

// Что правило вычитало из строки: узел, машинный вид остановки и тексты человеку.
// `outcome` — исход узла, с которым маршрут встал, когда он важен читателю отдельно от
// вида остановки: `exhausted` — тот же объявленный `human`, но без вердикта агента.
interface HaltMatch {
  stage: string | null;
  stop?: string;
  outcome?: 'exhausted';
  title: string;
  hint: string;
}

// Приставка комментария узла, которым route-runtime называет исчерпание бюджета заходов.
// Она же — единственный признак этой остановки в журналах, написанных до 22.09.2026:
// движок дописывал причину в строку остановки не всегда, а комментарий писал всегда.
const EXHAUSTED_COMMENT = 'исчерпан бюджет повторов';

/**
 * Причина остановки, у которой нет вердикта агента: узел исчерпал бюджет заходов, и ни один
 * из них результата не зафиксировал (таймаут, упавший процесс, лежащий провайдер).
 *
 * Собирается в одном месте, потому что источника у неё два: строка журнала (её пишет
 * движок) и комментарий узла в реестре (его пишет route-runtime). Вторым читаются уже
 * остановленные задачи, чья строка написана прежним движком: до этого правила такая
 * остановка попадала в «узел вернул решение человеку» и звала читать замечание, которого
 * агент не писал (t7989: три захода по 30 минут, план записан за 50 секунд до обрыва
 * третьего). Черновик хода при этом лежит в state и достанется следующему заходу.
 */
function exhaustedCause(stage: string | null, reason: string | null): HaltMatch {
  const named = stage ? `${stage}: ` : '';
  // Приставка в заголовке лишняя: «раннер не получил результат» уже сказало то же самое,
  // а место в строке нужно цифрам. В комментарии узла она остаётся — там свой контекст.
  // Прежняя формулировка движка («раннер не зафиксировал результат», без цифр) — тоже
  // пересказ заголовка: в таком заголовке одна и та же мысль стояла бы дважды.
  const detail = (reason || '')
    .replace(new RegExp(`^${EXHAUSTED_COMMENT}:?\\s*`), '')
    .replace(/^раннер не зафиксировал результат$/, '')
    .trim();
  return {
    stage,
    stop: 'human',
    outcome: 'exhausted',
    title: `${named}раннер не получил результат — ${detail || EXHAUSTED_COMMENT}`,
    hint: 'агент не успел отчитаться в лимит этапа или лежал провайдер; черновик хода'
      + ' t<TASK>.<этап>.checkpoint.md уцелел — «продолжить прогон» переиграет узел с'
      + ' него, а не с нуля; упирается во время раз за разом — подними класс времени'
      + ' этапа в профиле',
  };
}

// Правило разбора: регулярка формулировки движка и сборка причины по её группам.
// `weak` — итоговая строка диспетчера («fail-closed (код N)»): она печатается ПОСЛЕ
// строки с настоящей причиной, поэтому первой с конца попадается всегда она. Слабое
// правило не закрывает поиск — точная причина выше в окне выигрывает, а слабое остаётся
// ответом только когда назвать больше нечего.
interface HaltRule {
  re: RegExp;
  build: (m: RegExpExecArray) => HaltMatch;
  weak?: true;
}

// Найденная причина: разобранное правило плюс сама строка журнала и её время.
type StallCause = HaltMatch & { detail: string | null; since: string | null };

// Вход классификатора: реестр задачи, журнал (готовым списком или текстом) и живость демона.
export interface StallInput {
  registry?: Record<string, string | undefined>;
  timeline?: StallEvent[];
  logText?: string;
  daemonAlive: boolean;
}

// Ответ классификатора. `kind` отделяет объявленную остановку от молчаливого обрыва.
export interface StallInfo extends StallCause {
  kind: 'human' | 'crashed';
  fails: number | null;
  comment: string | null;
}

