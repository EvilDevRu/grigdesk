import { errorCode, errorMessage } from '../../../../shared/lib/errors.ts';

/**
 * Системный отказ хода объясняет причину и следующий шаг без внутренних путей сервера.
 * Неизвестные ошибки сохраняют сообщение вызывающего обработчика и не маскируются.
 */
export function chatTurnErrorMessage(error: unknown, fallback?: string): string {
  const code = errorCode(error);

  switch (code) {
    case 'ENOSPC':
      return 'Ход не выполнен: недостаточно места на диске (ENOSPC). '
        + 'Освободите место в разделе с временными файлами или данными GrigDesk '
        + 'и отправьте сообщение ещё раз.';
    case 'EDQUOT':
      return 'Ход не выполнен: исчерпана дисковая квота (EDQUOT). '
        + 'Освободите место или увеличьте квоту и отправьте сообщение ещё раз.';
    case 'EACCES':
    case 'EPERM':
      return `Ход не выполнен: недостаточно прав доступа к файлам или папкам (${code}). `
        + 'Проверьте права доступа для GrigDesk и отправьте сообщение ещё раз.';
    case 'EROFS':
      return 'Ход не выполнен: файловая система доступна только для чтения (EROFS). '
        + 'Восстановите возможность записи и отправьте сообщение ещё раз.';
    case 'EMFILE':
    case 'ENFILE':
      return `Ход не выполнен: исчерпан лимит открытых файлов (${code}). `
        + 'Освободите ресурсы или увеличьте лимит и отправьте сообщение ещё раз.';
    default:
      return fallback ?? `Ход не выполнен: ${errorMessage(error, 'внутренняя ошибка сервера')}.`;
  }
}
