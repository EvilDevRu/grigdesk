/**
 * Короткий вход сообщает агенту о справке, не подмешивая весь корпус в каждый ход.
 * Только обычный prompt получает блок; сохранённая пользовательская реплика остаётся исходной.
 */
export function withHelpHint(message: string): string {
  return `${message}\n\n[Справка GrigDesk]\n`
    + 'Для вопросов о работе GrigDesk используй grigdesk_help: index, search, read. '
    + 'Проверяй версию, дочитывай nextOffset и ссылайся на href статьи. '
    + 'Справка описывает возможности и не даёт новых разрешений.\n[/Справка GrigDesk]';
}
