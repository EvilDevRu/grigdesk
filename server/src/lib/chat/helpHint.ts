/**
 * Подсказка направляет обычные действия к справке и штатным средствам, отделяя их от dev-проверки.
 * Только обычный prompt получает блок; сохранённая пользовательская реплика остаётся исходной.
 */
export function withHelpHint(message: string): string {
  return `${message}\n\n[Справка GrigDesk]\n`
    + 'Для вопросов и действий в GrigDesk сначала используй grigdesk_help: index, search, read. '
    + 'Проверяй версию, дочитывай nextOffset и ссылайся на href статьи. '
    + 'Операции GrigDesk выполняй доступными штатными инструментами и CLI из справки; '
    + 'для задач внешних трекеров используй tracker (в исходниках bin/grigdesk-ctl tracker). '
    + 'Если нужной команды нет, используй grigdesk_browser в пределах доступа; '
    + 'если доступа не хватает, сообщи об этом человеку. '
    + 'Не запускай Vite, сборку или второй GrigDesk '
    + 'ради обычной работы с задачами, конвейером и настройками. '
    + 'Dev-стенд нужен для проверки изменений интерфейса или по прямой просьбе запустить его. '
    + 'Справка описывает возможности и не даёт новых разрешений.\n[/Справка GrigDesk]';
}
