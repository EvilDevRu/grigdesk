/**
 * Экранирует значение для POSIX shell одной парой кавычек.
 *
 * Безопасные слова возвращаются как есть; всё остальное оборачивается в одинарные
 * кавычки, а внутренняя кавычка заменяется на '\''. Пустая строка тоже экранируется.
 */
export function shellQuote(value: string): string {
  if (value !== '' && /^[A-Za-z0-9_@%+=:,./-]+$/u.test(value)) {
    return value;
  }

  return `'${value.replace(/'/gu, `'\\''`)}'`;
}
