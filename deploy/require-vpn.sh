#!/usr/bin/env bash
# Ворота VPN для кокпита: возвращает 0, только если трафик РЕАЛЬНО идёт через туннель.
# Ставится в ExecStartPre — при ненулевом коде systemd не запускает сервер и повторит
# попытку через RestartSec. Так после перезагрузки машины кокпит спокойно ждёт, пока
# поднимется sing-box, вместо того чтобы стартовать в обход VPN.
#
# ПОЧЕМУ НЕ ХВАТАЕТ ПРОВЕРКИ «ИНТЕРФЕЙС ЕСТЬ». sing-box поднимает singbox_tun и только
# потом расставляет правила маршрутизации. Между этими моментами интерфейс уже «up»,
# а трафик ещё идёт мимо — стартовать в это окно означает ровно ту утечку, от которой
# ворота и ставятся. Поэтому решает маршрут, а не наличие устройства.
#
# ПРО uid. sing-box маршрутизирует по владельцу сокета (`ip route get` показывает
# `uid 1000`, таблица 2022). Проверка обязана выполняться от того же пользователя, что
# и сервер, иначе ответ будет про чужой трафик. Для systemd --user это выполняется само.
set -uo pipefail

IFACE="${COCKPIT_VPN_IFACE:-singbox_tun}"
PROBE="${COCKPIT_VPN_PROBE:-1.1.1.1}"

fail() { echo "VPN-ворота: $1 — кокпит не стартует" >&2; exit 1; }

[[ -e "/sys/class/net/$IFACE" ]] || fail "нет интерфейса $IFACE (VPN не поднят)"

# tun-устройства часто рапортуют operstate=unknown — это норма, а не сбой.
oper=$(cat "/sys/class/net/$IFACE/operstate" 2>/dev/null || echo "?")
[[ "$oper" == "up" || "$oper" == "unknown" ]] || fail "$IFACE в состоянии '$oper'"

route=$(ip route get "$PROBE" 2>/dev/null | head -1)
[[ -n "$route" ]]                || fail "нет маршрута до $PROBE"
[[ "$route" == *"dev $IFACE"* ]] || fail "трафик до $PROBE идёт мимо туннеля ($route)"

echo "VPN-ворота: $IFACE поднят, трафик до $PROBE идёт через него — старт разрешён"
