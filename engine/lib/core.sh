# --- замкнутая область задачи в каждый агентский промпт ---
# Маршрут прибит хешем на старте попытки, поэтому исправление профильного prompt до уже
# идущей задачи не доедет. Граница scope — инвариант исполнения, а не особенность одного
# критика: её добавляет живой движок всем узлам. Это заодно не даёт артефактам агентов
# самопроизвольно становиться новыми требованиями и размыкать цикл «автор → проверяющий».
_stage_scope_block() {
  # Текст берём в КАВЫЧЕЧНОМ heredoc: в нём полно markdown-обратных кавычек, и в обычном
  # они стали бы подстановкой команд. Абсолютный путь движка поэтому подставляется после,
  # по метке. Путь обязан быть буквальным: право на команду — префиксное правило по СЫРОЙ
  # строке, и `$FACTORY_HOME/lib/stage-probe.sh` в команде агента не совпал бы с ним ни
  # разу, сколько бы переменная ни была экспортирована.
  local text review_policy

  if [[ "${FACTORY_LOOP_ROLE:-}" == lead || "${FACTORY_LOOP_ROLE:-}" == worker ]]; then
    review_policy=$(cat <<'EOF'
В режиме «цикл» прогресс оценивает ведущий по свежему результату и критериям задачи.
Повторное замечание возвращай исполнителю с проверенным остатком и конкретным заданием;
стабильный id сохраняй. Если ремонт не помог, выясни причину и измени подход, не объявляя
требование выполненным или отложенным. Новые замечания допустимы только в границах задачи.
Совпадение или уточнение id не останавливает передачу: каждый ремонт расходует круг
из `evidence.loop.maxRounds`. Планируй остаток по `evidence.loop.roundsLeft`.
EOF
)
  else
    review_policy=$(cat <<'EOF'
Если ты проверяющий узел, на первом проходе собери полный набор связанных с критериями
блокирующих замечаний. На повторном проходе после возврата этот набор **замкнут**:

- сначала перепроверь открытые `evidence.findings.open`, сохраняя прежний id для той же
  проблемы; переименование или дробление дефекта не считается новой находкой;
- новый id не продолжает автоматический цикл: если изменения после вердикта внесли новую
  регрессию, зафиксируй её с привязкой к критерию — runtime остановит расширение у человека;
- если после одного ремонта остался тот же набор id, не запускай ещё один ремонт уточнением
  формулировок: runtime зафиксирует `no-progress` и остановится у человека;
- пропущенная ранее проблема, уже существовавшая при прошлом вердикте, становится
  неблокирующим follow-up и не открывает ещё один цикл возврата.
EOF
)
  fi

  text=$(cat <<'EOF'
---

## Замкнутая область задачи (инвариант движка)

Область работы задают только описание и критерии приёмки задачи, явные исключения из них
и прямые решения человека в этой попытке. План раскладывает эти требования на изменения и
проверки, но не расширяет их. Разведка, отчёты, замечания критиков, найденный старый код и
мысленные мутации — доказательства, а не источник новых требований.

**Область не сужается узлом — только человеком.** Пустой список критериев не даёт свободы
трактовки: критерии тогда — пункты самой постановки как есть. «Уже есть в коде» пункт не
закрывает: постановка называет существующее недостаточным — значит, человек смотрел именно
на него. Ответы человека — ответы на конкретные вопросы, а не белый список области. Пункт,
который узел делать не будет, — не «карточка решения» в отчёте, а неуспех этапа с владельцем
`human` и вопросом (`plan` при противоречии пунктов). Для проверяющего невыполненный и не
закрытый человеком пункт — блокирующее замечание (`build` или `human`), а не отложенное.

Явный запрет команды и точная команда проверки в задаче — часть той же границы и сильнее
общего шаблона этапа или профиля. Запрещённую команду не запускай даже «для проверки»:
используй указанную в задаче безопасную замену. Если замены нет, зафиксируй проверку как
не выполненную с точной причиной и передай решение человеку, не подбирая похожую команду.

**«Не смог проверить» — НЕ блокирующее замечание.** Отказ прав, недоступный стенд или
отсутствующие данные говорят о твоём заходе, а не о работе автора: маршрут развернётся
туда, где чинить нечего. Отдавай такую находку отложенной, назвав проверку и препятствие.

Но сначала проверь сам. Однострочник проверяющему узлу запрещён, а опыт разрешён: тот же
код, только в одноразовом каталоге вне рабочего дерева и с питоном из venv проекта.

```
bash @FACTORY_HOME@/lib/stage-probe.sh --lang python <<'PY'
import importlib; print(importlib.util.find_spec("пакет"))
PY
```

Опыт, изменивший дерево, движок объявляет недействительным: опыт только читает. Языки —
`python|node|php|sh`; тем же способом воспроизводят дефект и снимают замер, а черновому
скрипту в рабочем дереве места нет.

**Грязное дерево — не находка и не твоя работа.** Конфигурацию стенда (env-файлы, схемы,
адреса сервисов) подставляет подъём песочницы: расхождение с базовой веткой там штатно.
Не возвращай такие файлы «к эталону» и не подавай состояние дерева замечанием — этим
ломается стенд, а не чинится дерево. `git status` показывает расхождение с базой, а не с
началом твоего захода; сверку до и после делает машинный сторож движка.

Каждое изменение кода, новый тест и **блокирующее** замечание обязаны ссылаться на точный
критерий или решение человека и объяснять, что именно останется невыполненным. Нет такой
связи — находка неблокирующая: она не требует реализации или теста в этой задаче и не
может быть причиной возврата по маршруту.

Отдавай такую находку отложенной, а не словами в комментарии:

```
stage-result.sh ... --finding-deferred <id>=<что нашёл и почему это вне цели задачи>
```

Отложенные находки не возвращают работу автору и не участвуют в сторожах топтания: они
едут хвостом до ворот приёмки и показываются человеку одним списком вместе с результатом.
Отказ, в котором не осталось ни одного блокирующего замечания, движок выпрямляет в `done`
с этим хвостом — held-маршрут по нечинимым замечаниям никому не нужен.

Граница одна и проверяется машиной: **блокирует только то, что ломает цель самой задачи
или является регрессией ранее работавшего.** Всё прочее — отложенная находка, даже если
дефект настоящий и ты уверен в нём. Не бывает «блокирующего, потому что важно».

Достаточное доказательство — прямая проверка каждого критерия и прямо названных в нём
границ. Не требуй перебора всех ветвей реализации, внутренних деталей или произвольных
гипотетических мутаций, если этого нет в критериях.

**Дефект, существующий на базовой ревизии, замечанием этой задачи не является** — ни
блокирующим, ни отложенным: отложенное это хвост ЭТОЙ работы, а чужой давний дефект туда
не относится. Инструмент почти всегда шире задачи (линтер — по всему файлу, прогон — по
всему spec-файлу), поэтому отдели своё от чужого: прогони ту же проверку на базовой
ревизии и вычти совпавшее либо ограничь охват инструмента диффом. Не смог разделить —
скажи это в отчёте и не подавай неразделённое блокирующим. Унаследованному место в
комментарии узла отдельным списком «было до задачи», а не в findings.

Цена ошибки несимметрична. Чужой дефект, поданный блокирующим, разворачивает маршрут к
автору; автор справедливо его не чинит; бюджет тратится на чужую работу.
Пропущенный чужой дефект не стоит ничего: он лежал в репозитории
и до задачи.

@REVIEW_RETURN_POLICY@

Если ты автор, вернувшийся от проверяющего, закрывай только его открытые замечания,
связанные с критериями. Не расширяй требования и матрицу проверок по собственной инициативе.

`evidence.findings.deferred` — отложенные находки: дефекты, признанные вне цели задачи.
Это НЕ твой долг и не повод для работы: не чини их по своей инициативе, не пиши по ним
тесты и не считай их незакрытыми. Они существуют, чтобы человек увидел их на воротах.
Исключение одно: человек прямо вернул маршрут с требованием починить конкретную отложенную
находку — тогда она названа в его указании и становится обычной работой этого захода
наравне с открытыми замечаниями.
EOF
)
  text=${text//@REVIEW_RETURN_POLICY@/$review_policy}

  printf '%s\n' "${text//@FACTORY_HOME@/$FACTORY_HOME}"
}

# --- карточка самостоятельного решения в промпт ---
# Принцип автономности: конвейер решает сам и предъявляет решение в приёмке, а не встаёт
# посреди маршрута с вопросом, на который человек всё равно не пойдёт смотреть. Замер по
# живым прогонам: одна такая остановка стоила 14 часов простоя стенда и слота ради одного
# `goto`, вторая — 31 минуты, в которые человек работал курьером между тем же ИИ и полем
# причины. Знания он не добавил ни разу: разбор в обоих случаях делала модель.
#
# Цена права решать самому названа прямо: конвейер, который сам обновляет эталон, так же
# тихо примет регресс. Защита ровно одна — карточка в отчёте приёмки вместе с
# доказательством, потому что к готовой работе человек приходит и так.
#
# Адрес карточки — `artifacts.report`, а не собственный файл. Это и есть отчёт приёмки:
# ворота `gate_accept` показывают именно его, и узлы маршрута уже дописывают туда свои
# сводки (так же поступает досье аудита). Свой артефакт потребовал бы ключа в контексте
# движка, allowlist сервера и записи в карте документов узла — трёх мест, которые
# расходятся молча.
_stage_decision_card_block() {
  cat <<'EOF'
---

## Решил сам — предъяви карточкой

Решение, которого нет в задаче (сменил эталон, выбрал из равнозначных вариантов, признал
проверку неприменимой), принимать можно; молча — нельзя. Допиши в `artifacts.report`:

1. что сделал — одной фразой;
2. почему — обычными словами;
3. чем доказал — что запускал и что вышло;
4. чем грозит ошибка — как человек её увидит;
5. подробности — файлы, строки, коммиты.

**Первые четыре пункта читаются без открытия репозитория.** Путь или хеш в них — дефект
карточки: человек приходит к готовой работе и по ним ничего не восстановит.
EOF
}

# --- контекст повтора в промпт ---
# Ретрай начинается с чистого листа: движок помнит, что заход не первый, а агент — нет.
# Без контекста повторный BUILD переделывает уже написанный код. Следы предыдущего захода
# никуда не делись — заставляем сначала посмотреть.
# Повтор без результата — ЗАКРЫВАЮЩИЙ заход, а не второй разбор. Прежний блок лишь
# просил «доделать, а не переписывать», и агент это исполнял буквально: читал черновик,
# а затем заново поднимал веер ролей, потому что этого требовал промпт узла. Живой замер
# (t7989, узел плана): три захода по 30 минут, в каждом три независимые роли с нуля, план
# записан на третьем за 50 секунд до обрыва, результат не зафиксирован ни разу. Для
# no-result третий аргумент — класс исхода прошлого захода (timeout, crashed…): после
# таймаута бюджет времени съеден целиком, и это называется прямо.
_stage_retry_block() {
  local n=$1 reason=$2 note=${3:-} what
  case "$reason" in
    no-result)
      what='оборвался, не зафиксировав результат (таймаут или падение процесса)'
      [[ "$note" != timeout ]] ||
        what='убит по лимиту времени этапа, не успев зафиксировать результат'
      ;;
    failed)    what='закончился отказом по существу задачи' ;;
    # Сдачу отверг хост, а не агент: работа сделана и лежит в дереве, не принято только
    # доказательство. Без цитаты причины повтор переделывал бы всё и сдавал то же самое.
    evidence-rejected) what='был сдан как `done`, но хост-сторож эту сдачу отверг' ;;
    *)         what='не довёл этап до конца' ;;
  esac
  cat <<EOF
---

## Это повтор этапа (заход $n)

Предыдущий заход $what. Движок считает этап невыполненным, но следы работы остались:
правки в рабочем дереве, черновики, записи в артефактах.
EOF
  if [[ "$reason" == evidence-rejected ]]; then
    cat <<EOF

**Причина отказа сторожа:** ${note:-сторож причину не назвал; сверь сдачу с требованиями
этапа к артефактам и доказательствам}.

Устрани ровно это и сдай снова через \`stage-result\`. Остальную работу не переделывай:
второй такой же отказ остановит маршрут и отдаст его человеку.
EOF
  fi
  if [[ "$reason" == no-result ]]; then
    cat <<EOF

Это закрывающий заход, а не второй разбор. Не поднимай заново параллельные роли,
разведку и поиски, даже если задание узла их требует: их результат уже в черновике хода
и в артефактах на диске — продолжай с них. Сначала прикинь по черновику остаток. Если
работа по существу сделана — сверь её и сразу фиксируй через \`stage-result\`; если нет —
доделывай ровно недостающее. К мягкому сроку регламента результат должен быть
зафиксирован в любом состоянии.
EOF
  fi
  cat <<EOF

Начни с осмотра сделанного — \`git status\` и \`git diff\` в рабочем дереве, отчёты
предыдущих узлов. Доделай недостающее и проверь целостность, а не переписывай заново:
переделка с нуля стоит столько же, сколько первый заход, и так же рискует не уложиться.
EOF
}

# --- незакрытые находки проверяющих узлов в промпт ---
# Возврат по `failed` — это разговор двух узлов: критик пишет типизированные находки
# (`stage-result.sh --finding`), диспетчер возвращает курсор автору. Но текст находок
# доезжал до автора ТОЛЬКО если маршрут объявил у него `evidence` в requiredContext:
# `render_node` вклеивает в промпт ровно перечисленные секции. Ни один профиль не делал
# это последовательно (замер 22.08.2026 по всем локальным профилям: узел плана слеп
# везде, узлы автора тестов и реализации — через один; один профиль чинил свой узел
# точечно, общего правила не завёл). Слепой автор входил с прежним заданием, делал то же
# самое, критик находил те же дефекты слово в слово — и попытка умирала об `no-progress`
# через два круга по 25 минут.
#
# Валидатором маршрута это чинить нельзя: `validate_machine` работает и на ЧТЕНИИ бандла,
# поэтому новое требование сделало бы невалидными все уже опубликованные каталоги прямо
# посреди идущих прогонов. Значит доставка находок — инвариант ДВИЖКА, а не решение автора
# схемы: блок собирается из того же контекста, что уже построен для узла, и появляется
# независимо от requiredContext.
#
# Показываем только `open`: закрытые находки — история, отложенные адресованы человеку на
# воротах, а тут список к ремонту. Блок идёт ПЕРЕД словом человека: указание человека
# сильнее любых машинных находок.
_stage_open_findings_block() {
  local findings=$1 rendered
  rendered=$(printf '%s' "$findings" | python3 -c '
import json, sys

try:
    records = json.load(sys.stdin)
except (ValueError, json.JSONDecodeError):
    raise SystemExit(1)
if not isinstance(records, list) or not records:
    raise SystemExit(9)


def sequence(record, key):
    # bool в питоне является int, а `true` в номере захода — это повреждённая
    # проекция, а не первый заход: диагноз по ней был бы выдуман.
    value = record.get(key)
    return value if isinstance(value, int) and not isinstance(value, bool) else None


lines = []
looped = []
for record in records[:50]:
    if not isinstance(record, dict):
        continue
    source = str(record.get("sourceNode") or "?")
    if record.get("source", {}).get("phase") == "bootstrap":
        source = "bootstrap/" + source
    ident = str(record.get("id") or "?")
    summary = " ".join(str(record.get("summary") or "").split())
    opened = sequence(record, "openedSequence")
    last_seen = sequence(record, "lastSeenSequence")
    # Находку, которую проверяющий увидел СНОВА после ремонта, движок уже отличает
    # от свежей: openedSequence остаётся первым появлением, lastSeenSequence растёт
    # с каждым повторным вердиктом. Агент видел оба числа и раньше — но как числа,
    # а не как диагноз, и потому заходил на третий круг с тем же подходом.
    repeated = opened is not None and last_seen is not None and last_seen > opened
    mark = " — ПЕРЕЖИЛА РЕМОНТ" if repeated else ""
    if repeated:
        looped.append(ident)
    lines.append(f"- [{source} · {ident}] {summary}{mark}")
if not lines:
    raise SystemExit(9)

print("\n".join(lines))

if looped:
    shown = ", ".join(looped[:3])
    if len(looped) > 3:
        shown += f" и ещё {len(looped) - 3}"
    print(
        f"""
### Диагноз движка: по этим находкам заход уже не первый

Пережили ремонт: {shown}. Проверяющий увидел их СНОВА после того, как их уже чинили,
то есть прошлый подход к ним не сработал.

Повторять его нельзя, и уточнением формулировки это не обходится: движок сравнивает
набор идентификаторов, а не текст. Ещё один такой же вердикт он зафиксирует как топтание
и остановит маршрут — работа встанет до человека, а он придёт не скоро.

Выбери одно из двух и сделай это ЯВНО, в отчёте:

- почини иначе — и назови, чем новый подход отличается от прошлого;
- объяви, что закрыть нельзя, и назови причину: чего не хватает (прав, доступа, решения
  человека) или чем находка не подтверждается фактами.

Второе — законный исход захода, а не поражение. Молчаливый третий круг с тем же подходом
стоит дороже: он сжигает время этапа и всё равно заканчивается остановкой."""
    )
') || return 1
  [[ -n "$rendered" ]] || return 1
  cat <<EOF
---

## Незакрытые находки проверяющих узлов

Это typed-находки из журнала попытки: их оставили проверяющие узлы, и они до сих пор
НЕ закрыты. В скобках — узел, который нашёл, и идентификатор находки.

$rendered

Если узел вернулся сюда после отказа проверяющего, эти находки и есть причина возврата:
закрывай их адресно. Повторить прошлый заход, не тронув их, нельзя — проверяющий найдёт
то же самое, и маршрут остановится без прогресса.

Находку, которую считаешь неверной, не игнорируй молча: скажи в отчёте, чем именно она
не подтверждается фактами. Находку вне цели задачи отметь отложенной, а не закрывай.
EOF
}

# --- уже отложенные находки в промпт ---
# Обратная сторона предыдущего блока. Отложенная находка не требует работы, но и не
# перестаёт существовать: проверяющий узел, не видя её, находит ТО ЖЕ САМОЕ следующим
# кругом (замер: 8 попыток из 29 переоткрывают тот же id, одна — трижды). Каждый повтор
# занимает место в лимите находок вердикта, а человеку на воротах приходится второй раз
# говорить «это мы уже отложили».
#
# Список намеренно короче открытых находок: это справка, а не задание. Ни сводок, ни
# диагнозов — только id и одна строка, чтобы узел узнал находку и прошёл мимо.
_stage_deferred_findings_block() {
  local findings=$1 rendered
  rendered=$(printf '%s' "$findings" | python3 -c '
import json, sys

try:
    records = json.load(sys.stdin)
except (ValueError, json.JSONDecodeError):
    raise SystemExit(1)
if not isinstance(records, list) or not records:
    raise SystemExit(9)

lines = []
for record in records[:30]:
    if not isinstance(record, dict):
        continue
    ident = str(record.get("id") or "?")
    summary = " ".join(str(record.get("summary") or "").split())
    node = str(record.get("sourceNode") or "?")
    phase = (record.get("source") or {}).get("phase", "route")
    origin = f"bootstrap/{node}" if phase == "bootstrap" else node
    lines.append(f"- [{origin}/{ident}] {summary}")
if not lines:
    raise SystemExit(9)
print("\n".join(lines))
') || return 1
  [[ -n "$rendered" ]] || return 1
  cat <<EOF
---

## Уже отложенные находки

Эти дефекты признаны вне цели задачи и ждут человека на воротах приёмки.

$rendered

Работой они не являются. Не чини их, не пиши по ним тесты и **не подавай их заново** —
ни блокирующими, ни отложенными: они уже записаны. Исключение одно: человек прямо
потребовал починить конкретную из них в своём указании.
EOF
}

# --- указание человека при возврате курсора в промпт ---
# Свободный текст от человека доезжал до агента только через решения ВОРОТ. У обычного
# узла канала не было: кнопка «перейти сюда» писала причину в журнал попытки и на этом
# всё — агент входил с тем же заданием и повторял ту же ошибку. Разбор приходилось
# протаскивать через черновик хода, то есть мимо журнала, а журнал — главный инвариант.
# Блок идёт ПОСЛЕДНИМ и прямо объявляет приоритет: черновик выше по промпту зовёт
# «продолжай с этого места», а человек мог вернуть узел именно чтобы свернуть с него.
_stage_human_note_block() {
  local note=$1 quoted
  # Указание бывает многострочным (перечень точек правки, таблица замеров, запреты),
  # а markdown-цитата держится только пока `> ` стоит в начале КАЖДОЙ строки: без
  # префикса второй абзац выпадал из цитаты и читался как текст движка.
  quoted=$(printf '%s\n' "$note" | sed 's/^/> /')
  cat <<EOF
---

## Указание человека при возврате на этот узел

Узел не пришёл сюда сам: человек вернул на него курсор и оставил указание.

$quoted

Это главное в задании. Если оно расходится с черновиком предыдущего захода или с
отчётами прошлых узлов — прав человек, а расхождение назови в отчёте. Если указание
невыполнимо или неверно по фактам, не выполняй его молча и не выдумывай обход:
зафиксируй результат с объяснением, что именно не сходится.
EOF
}

# Вопрос и ответ bootstrap идут через файл: полный Unicode-текст не помещается
# в один argv/env на предельной длине. Закреплённый prompt при этом не меняется.
_stage_bootstrap_decision_block() {
  python3 - "$1" <<'PYDECISION'
import json, sys
from pathlib import Path
value = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
question, decision = value["stop"], value["decision"]
print("## Решение человека для разведки SCOUT\n")
print(f"Визит вопроса: {question['visitId']}; stop hash: {question['recordHash']}.")
print("\nВопрос предыдущей разведки:")
for line in question["reason"].splitlines():
    print("> " + line)
for finding in (question.get("verdict") or {}).get("findings", []):
    print("> " + finding["summary"])
print("\nОтвет человека:")
for line in decision["answer"].splitlines():
    print("> " + line)
print("\nЭто решение относится к указанному вопросу. Учти его в новом заходе SCOUT.")
PYDECISION
}

# --- один синхронный прогон агента для этапа ---
# $1=TASK $2=промпт. Выбранный runner делает ОДИН этап и завершается; bash ждёт.
run_agent() {
  local t=$1 prompt=$2 stage=${3:-}
  [[ -n "$stage" ]] || return 2
  # Рабочий каталог — WORKTREE ЗАДАЧИ, если профиль умеет его назвать. Пока cwd был общим
  # репозиторием, агенты складывали туда скриншоты, правили код и запускали eslint --fix
  # по всему проекту: 48 изменённых файлов в бэкенде и 277 во фронте основного стенда.
  local cwd="${PROFILE_AGENT_CWD:-$HOME}"
  if declare -F profile_agent_cwd >/dev/null; then
    local c2; c2=$(profile_agent_cwd "$t" 2>/dev/null)
    [[ -n "$c2" && -d "$c2" ]] && cwd="$c2"
  fi
  cd "$cwd" 2>/dev/null || true
  # --add-dir ОБЯЗАТЕЛЕН: агент работает в каталоге проекта, а реестр/план/отчёты фабрики лежат
  # в STATE_DIR за его пределами. Без этого песочница режет запись, и агент, отработав десятки
  # минут, не может выставить статус этапа — движок считает этап незавершённым и гоняет его заново.
  # FACTORY_HOME нужен для run-scoped stage-result/stage-progress и служебных команд движка.
  # Лимит времени этапа: браузерные замеры и прогон сценариев идут дольше правки кода.
  # Убитый по таймауту агент теряет ВСЮ работу этапа, поэтому лимит должен быть осознанным.
  local tmo; tmo=$(_stage_timeout "$t" "$stage")
  local ckpt; ckpt=$(_stage_checkpoint_path "$t" "$stage")
  export FACTORY_STAGE_CHECKPOINT="$ckpt"
  # Деревья, которые опыт узла обязан оставить нетронутыми. Называет их движок: сам
  # `stage-probe.sh` знает только свой cwd, а у задачи рабочих деревьев бывает несколько.
  export FACTORY_PROBE_ROOTS="${PROFILE_AGENT_DIRS:-}"
  # Предпроверка сдачи: исполняемый файл профиля, который `stage-result.sh` запускает ДО
  # записи done/skipped, пока агент жив и может исправиться. Хостовый evidence-хук после
  # раннера остаётся источником истины — это лишь его ранняя копия в руках агента: без неё
  # отказ приходил post-mortem, узел вставал, а причину человек носил агенту сам (t8702).
  # Путь резолвится здесь, в процессе с загруженным профилем: в оболочке агента хуков нет.
  local result_check=""
  if declare -F profile_stage_result_check >/dev/null; then
    result_check=$(profile_stage_result_check "$t" "$stage" 2>/dev/null) || result_check=""
    [[ -n "$result_check" && -f "$result_check" && -x "$result_check" ]] || result_check=""
  fi
  export FACTORY_STAGE_RESULT_CHECK="$result_check"
  # Карта идёт ПЕРВОЙ из служебных блоков: это справочник, а не указание заходу. Хвост
  # промпта занят тем, что направляет ход (регламент, повтор, черновик, слово человека),
  # и отдавать его самому объёмному блоку нельзя. Сам файл разведки — не приложение к
  # промпту: агент читает и ДОПИСЫВАЕТ его, поэтому путь назван в блоке дословно.
  local recon; recon=$(_stage_task_map_path "$t")
  export FACTORY_STAGE_TASK_MAP="$recon"
  if [[ -s "$recon" && ! -L "$recon" ]]; then
    local map_block; map_block=$(_stage_task_map_block "$recon")
    [[ -z "$map_block" ]] || prompt+=$'\n\n'"$map_block"
  fi
  # Scope идёт после справочной карты, но раньше регламента/памяти/слова человека.
  # Последнее может явно изменить границу; всё остальное обязано ей подчиняться.
  prompt+=$'\n\n'"$(_stage_scope_block)"
  prompt+=$'\n\n'"$(_stage_decision_card_block)"
  prompt+=$'\n\n'"$(_stage_time_budget_block "$tmo" "$ckpt")"
  # Правила записи — сразу за регламентом: оба про среду этапа, а не про его задачу. Блок
  # есть только у проверяющего узла: пишущему узлу права ничего из перечисленного не закрывают.
  local fs_block; fs_block=$(_stage_filesystem_block "$t")
  [[ -z "$fs_block" ]] || prompt+=$'\n\n'"$fs_block"
  local retry_no="${FACTORY_STAGE_RETRY:-}"
  if [[ "$retry_no" =~ ^[2-9]|^[0-9]{2,}$ ]]; then
    prompt+=$'\n\n'"$(_stage_retry_block "$retry_no" "${FACTORY_STAGE_RETRY_REASON:-}" \
      "${FACTORY_STAGE_RETRY_NOTE:-}")"
  fi
  # Черновик отдаём по НАЛИЧИЮ файла, а не по счётчику захода: после убитого оркестратора
  # resume входит в узел заново с номером 1.
  if [[ -s "$ckpt" && ! -L "$ckpt" ]]; then
    prompt+=$'\n\n'"$(_stage_checkpoint_block "$ckpt")"
  fi
  # Незакрытые находки — после черновика: черновик говорит «вот что я успел», находки —
  # «вот что в этом до сих пор не так». Пустой список и повреждённый JSON блока не дают
  # (функция возвращает ненулевой код), поэтому отсутствие находок ничем не пахнет.
  if [[ -n "${FACTORY_STAGE_OPEN_FINDINGS:-}" ]]; then
    local findings_block
    if findings_block=$(_stage_open_findings_block "${FACTORY_STAGE_OPEN_FINDINGS}"); then
      prompt+=$'\n\n'"$findings_block"
    fi
  fi
  # Отложенные — сразу за открытыми: сначала «что чинить», потом «что уже решено не чинить».
  # Обратный порядок читался бы как список работы.
  if [[ -n "${FACTORY_STAGE_DEFERRED_FINDINGS:-}" ]]; then
    local deferred_block
    if deferred_block=$(_stage_deferred_findings_block "${FACTORY_STAGE_DEFERRED_FINDINGS}"); then
      prompt+=$'\n\n'"$deferred_block"
    fi
  fi
  # Последним — чтобы не потеряться за черновиком и регламентом: это единственный блок,
  # который написал человек, а не движок.
  if [[ -n "${FACTORY_STAGE_HUMAN_NOTE:-}" ]]; then
    prompt+=$'\n\n'"$(_stage_human_note_block "${FACTORY_STAGE_HUMAN_NOTE}")"
  fi
  if [[ -n "${FACTORY_STAGE_BOOTSTRAP_DECISION_FILE:-}" ]]; then
    prompt+=$'\n\n'"$(_stage_bootstrap_decision_block "$FACTORY_STAGE_BOOTSTRAP_DECISION_FILE")"
  fi
  # Порог автосжатия контекста этапа. Собственный порог CLI — доля ОКНА модели, а у окна
  # в миллион токенов он срабатывает около 959k: то есть в дорогой зоне (выше ~250k кэш
  # промпта перестаёт совпадать и переписка пишется заново по двойному тарифу вместо чтения
  # по десятой доле) он не включается никогда. Значение приезжает из GrigDesk явным --setenv,
  # а для запусков из CLI берётся из `runners.env` профиля; `0` — не вмешиваться.
  # Диалект переменной знает раннер, движок держит одно нейтральное имя.
  local auto_compact=${FACTORY_STAGE_AUTO_COMPACT:-}
  if [[ -z "$auto_compact" && -n "${PROFILE_NAME:-}" ]]; then
    local ac_cfg; ac_cfg=$(multi_runner_config_file 2>/dev/null) || ac_cfg=''
    if [[ -n "$ac_cfg" && -f "$ac_cfg" ]]; then
      auto_compact=$(profile_config_get "$ac_cfg" AUTO_COMPACT_WINDOW)
    fi
  fi
  [[ "$auto_compact" =~ ^[0-9]+$ ]] || auto_compact=0
  # Разрешённое значение уезжает раннерам ОТДЕЛЬНЫМ именем, а не обратно в исходную
  # переменную: bash закрепляет присвоение перед вызовом функции, если функция сама в него
  # пишет, — и порог, заданный одному этапу, стал бы «настройкой» для всех следующих заходов
  # демона. Имя в стиле соседних RUNNER_*: вход движка отдельно, вывод раннеру отдельно.
  export RUNNER_AUTO_COMPACT_WINDOW="$auto_compact"
  export RUNNER_CLAUDE_SETTINGS RUNNER_CLAUDE_CONTROL_DIR
  RUNNER_CLAUDE_SETTINGS=$(_agent_settings "$stage" "$t") || return
  RUNNER_CLAUDE_CONTROL_DIR=$CONTROL_DIR
  export RUNNER_CLAUDE_ADD_DIRS="$STATE_DIR ${PROFILE_AGENT_DIRS:-}"
  export RUNNER_CODEX_ADD_DIRS="$STATE_DIR ${PROFILE_AGENT_DIRS:-}"
  export RUNNER_KIMI_ADD_DIRS="$STATE_DIR ${PROFILE_AGENT_DIRS:-}"
  # DeepSeek V1 не получает дополнительные writable roots: список остаётся только
  # prompt-контекстом движка, а DSH sandbox пишет ровно в cwd сессии.
  export RUNNER_DEEPSEEK_ADD_DIRS="$STATE_DIR ${PROFILE_AGENT_DIRS:-}"

  # Shared-профиль может дать агенту узкий engine-owned control channel. Hook
  # стартует до provider CLI, stop выполняется при любом результате runner-а.
  # Это не lifecycle стенда: broker только исполняет заранее разрешённые команды
  # существующего ресурса. Codex сам монтирует control dir read-only — добавлять
  # его в общий writable --add-dir нельзя.
  local agent_control_started=0 runner_rc stop_rc=0
  local has_agent_control_start=0 has_agent_control_stop=0
  declare -F profile_agent_control_start >/dev/null && has_agent_control_start=1
  declare -F profile_agent_control_stop >/dev/null && has_agent_control_stop=1
  (( has_agent_control_start == has_agent_control_stop )) || return 78
  if (( has_agent_control_start )); then
    profile_agent_control_start "$t" "$stage" || return
    agent_control_started=1
    if [[ -n "${PROFILE_AGENT_CONTROL_DIR:-}" ]]; then
      RUNNER_CLAUDE_ADD_DIRS+=" $PROFILE_AGENT_CONTROL_DIR"
    fi
    export RUNNER_CODEX_ADD_DIRS RUNNER_CLAUDE_ADD_DIRS
  fi
  multi_runner_run "$t" "$prompt" "$stage" "$tmo"
  runner_rc=$?
  if (( agent_control_started )); then
    profile_agent_control_stop "$t" "$stage" "$runner_rc" || stop_rc=$?
  fi
  (( stop_rc == 0 )) || return 75
  return "$runner_rc"
}
