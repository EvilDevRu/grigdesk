Разведка уже прошла по коду и назвала места, которых касается задача. Это экономит твои
раунды: каждый поиск — отдельный запрос к модели, а его результат потом едет в контексте
всех следующих запросов этого захода и оплачивается заново каждым из них.

$body

Как этим пользоваться:

- файл назван в карте — **открывай его напрямую**, не выясняй расположение поиском
  (\`grep\`, \`rg\`, \`ls\`, \`find\`);
- нужного в карте нет — ищи, но **допиши найденное в раздел «Карта задачи»** файла
