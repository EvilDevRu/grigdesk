#!/usr/bin/env bash
# Ядро движка фабрики — AGNOSTIC. Не знает о проектах: всё проектное берётся из профиля
# (см. ../docs/engine/PROFILE-CONTRACT.md). Здесь: реестр статусов, ворота, resume-цикл, flock, таймауты.
# Подключается из bin/factory. Требует, чтобы профиль уже был подгружен (source).

FACTORY_HOME="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
STATE_DIR="${STATE_DIR:-$HOME/.factory/state}"
LOGDIR="$STATE_DIR/logs"; mkdir -p "$LOGDIR" "$STATE_DIR/archive"
NODE_TIMEOUT="${FACTORY_STAGE_TIMEOUT:-1800}"   # таймаут одного этапа (сек)
# shellcheck disable=SC1091
source "$FACTORY_HOME/lib/multi-runner.sh"
# shellcheck disable=SC1091
source "$FACTORY_HOME/lib/workspace-guard.sh"
CONTROL_DIR=$(factory_control_root) || {
  echo "Некорректный FACTORY_CONTROL_ROOT: control metadata не должна пересекаться с STATE_DIR" >&2
  return 78 2>/dev/null || exit 78
}
mkdir -p "$CONTROL_DIR"
[[ ! -L "$CONTROL_DIR" && "$(realpath -e -- "$CONTROL_DIR" 2>/dev/null)" == "$CONTROL_DIR" ]] || {
  echo "Небезопасный FACTORY_CONTROL_ROOT: symlink запрещён" >&2
  return 78 2>/dev/null || exit 78
}
chmod 700 "$CONTROL_DIR" 2>/dev/null || true

# --- вторичный реестр статусов: host/control projection ---
_pf() { echo "$STATE_DIR/t${1}.pipeline"; }
set_st() {
  local t=$1; shift
  if [[ "${1:-}" == --init ]]; then
    shift
    [[ "${1:-}" == --stages ]] || return 78
    shift
    local stages=${1:-}; shift
    pipeline_store_route_init "$t" "$stages" "$@"
    return
  fi
  run_state_control_update "$t" "$@"
}
get() { grep "^$2=" "$(_pf "$1")" 2>/dev/null | tail -1 | cut -d= -f2- || true; }
set_stage_terminal() {
  local t=$1 stage=$2 result=$3; shift 3
  run_state_control_update "$t" "$stage" "$result" "$@"
}
# Пишем ТОЛЬКО в файл: stdout демона и так перенаправлен в этот же журнал (bin/factory),
# поэтому tee давал каждую строку дважды и журнал читался как «всё случилось два раза».
flog() { echo "$(date '+%F %T') [t${1}] ${*:2}" >>"$LOGDIR/t${1}.stages.log"; }

# --- доверенные standalone-настройки агента ---
# Route runner отключает user/project/local sources, поэтому этот engine-owned файл
# содержит весь session policy.
#
# ВРЕМЕННО СНЯТО: обязательная native OS sandbox граница (`"sandbox":{"enabled":true,
# "failIfUnavailable":true,"allowUnsandboxedCommands":false,…}`). На Linux эта песочница —
# bwrap, то есть user namespace: в нём отображены только uid/gid 1000, а дополнительные
# группы теряются. Значит `/var/run/docker.sock` (root:docker 0660) виден агенту как
# nobody:nogroup и недоступен, а сеть уходит в свой namespace, где localhost-порт стенда
# просто «в соединении отказано». Рантайм-этапы ходят в стенд ровно этими двумя каналами
# (docker exec + API), поэтому REPRO может видеть код, но не получить ни одного
# рантайм-сигнала. `allowUnsandboxedCommands:false` закрывал и escape-hatch, так что
# обойти было нечем. Вернуть границу можно только вместе с каналом до стенда: сокет-прокси
# от своего uid (per-path allowUnixSockets на Linux не работает — только allowAllUnixSockets)
# либо песочница по классу узла. Подробности — ../docs/engine/ENGINE.md.
# Мало дать доступ к каталогам: статус этапа выставляется КОМАНДОЙ, а bash-команды одобряются
# отдельно от правок файлов. Без этого агент доходит до последнего шага и просит разрешение —
# в неинтерактивном режиме это значит «этап не завершён» и повтор с нуля.
# Профиль может добавить свои команды через массив PROFILE_AGENT_ALLOW (например прогон тестов).
_agent_settings() {
  local stage=${1:-} task=${2:-} settings_key
  [[ -z "$stage" || "$stage" =~ ^[A-Z][A-Z0-9_]{0,63}$ ]] || return 78
  [[ -z "$task" || "$task" =~ ^[1-9][0-9]{0,18}$ ]] || return 78
  settings_key=${stage:-any}
  [[ -z "$task" ]] || settings_key="t${task}-${settings_key}"
  local f="$CONTROL_DIR/agent-settings-${settings_key}.json" rules extra="" tmp tool_control
  if declare -p PROFILE_AGENT_ALLOW >/dev/null 2>&1; then
    local r
    for r in "${PROFILE_AGENT_ALLOW[@]}"; do extra+=",\"$r\""; done
  fi
  # Чувствительные команды профиль выдаёт по роли узла. Глобальный массив
  # остаётся для безопасных общих инструментов и обратной совместимости профилей.
  if [[ -n "$stage" ]] && declare -F profile_stage_agent_allow >/dev/null; then
    local stage_extra r
    stage_extra=$(profile_stage_agent_allow "$stage") || return
    while IFS= read -r r || [[ -n "$r" ]]; do
      [[ -n "$r" ]] || continue
      [[ "$r" != *'"'* && "$r" != *$'\t'* && "$r" != *$'\r'* ]] || return 78
      extra+=",\"$r\""
    done <<<"$stage_extra"
  fi
  # Базовый набор: без него этап не может ни осмотреться, ни записать свой отчёт. В одном
  # прогоне накопились сотни отказов Bash/Write, включая запись t<TASK>.recon.md
  # в каталог самой фабрики. Отказ в неинтерактивном режиме не виден: агент молча перебирает
  # формулировки команды, тратит минуты и деньги, а отчёт этапа не появляется вовсе.
  # Опасное (автоформатирование) режется отдельно, в deny ниже — оно сильнее allow.
  # Абсолютный путь в правиле пишется с ДВУМЯ слэшами. С одним CLI считает путь
  # относительным проекту, и правило не совпадает ни с чем — молча, без ошибки.
  # Замер живым `claude -p`: с `Edit(/tmp/X/proj/**)` агент создал оба файла, с
  # `Edit(//tmp/X/proj/**)` — ответил «нет разрешения на запись» и не создал ни одного.
  # Ту же форму давно использует `Read(//**)` строкой ниже и запрет control root.
  [[ "$STATE_DIR" =~ ^/[A-Za-z0-9._/@%+=,:~-]+$ ]] || return 78
  local tool_state="//${STATE_DIR#/}"
  local base='"Write('"$tool_state"'/**)","Edit('"$tool_state"'/**)","Read(//**)"'
  base+=',"Bash(git:*)","Bash(git -C:*)","Bash(grep:*)","Bash(rg:*)","Bash(ls:*)","Bash(cat:*)"'
  base+=',"Bash(head:*)","Bash(tail:*)","Bash(wc:*)","Bash(find:*)","Bash(sed:*)","Bash(awk:*)"'
  base+=',"Bash(docker exec:*)","Bash(docker compose exec:*)","Bash(php:*)","Bash(node:*)"'
  base+=',"Bash(npx eslint:*)","Bash(npx vue-tsc:*)","Bash(npm run:*)","Bash(curl:*)","Bash(python3:*)"'
  # `cd` — потому что CLI разбирает СОСТАВНУЮ команду по частям, и решает самая слабая.
  # Замер по журналам всех прогонов: 1240 отказов Bash, 88% из них составные, и первым
  # по частоте блокирующим куском идёт `echo` (1178), вторым `cd` (357) — при том что
  # `git status && cd … && git status` состоит из уже разрешённого. Отказ ничего не
  # запрещает по существу: агент переписывает команду или, хуже, подменяет проверку
  # похожей и выдаёт её результат за требуемый. Сам `cd` записать не может ничего.
  base+=',"Bash(cd:*)"'
  # `echo`/`printf` теперь выдаются ВСЕМ узлам, включая проверяющие. Раньше проверяющему их
  # не давали: `echo x > file` префиксным правилом не выражается, и разрешение разменяло бы
  # предупредительный рубеж на посмертного сторожа, который валит узел уже после сорока
  # минут работы. Цена запрета оказалась крупнее: из 1302 отказов прав в журналах всех
  # прогонов `echo`/`printf` участвует примерно в 610, и перенаправление содержат лишь 12%
  # из них — остальное метки-разделители и хвост `; echo "exit=$?"`, которые записать не
  # могут ничего, но валят составную команду целиком.
  # Рубеж не исчез, а переехал туда, где видно команду ЦЕЛИКОМ: PreToolUse-хук
  # `stage-write-guard.sh` ниже. Он и строже прежнего правила — ловит запись в worktree
  # любой командой, а не только `echo` (замер по 3265 живым командам проверяющих узлов:
  # 8 срабатываний на ранее прошедших командах, 7 из них — настоящие `git show HEAD:… >
  # <worktree>/файл`, то есть оплаченный инцидент из docs/grigdesk/gotchas.md).
  base+=',"Bash(echo:*)","Bash(printf:*)"'
  # Питон проекта. В allowlist стоит только системный `python3`, а питон-проект живёт в
  # venv: `<repo>/.venv/bin/python` не совпадал ни с одним правилом, и любая проверка через
  # него отказывалась молча (замер: 33 таких отказа, 28 из них на проверяющем узле).
  # Спрашиваем ФАЙЛОВУЮ СИСТЕМУ, а не имя профиля: имя придумывает человек, каталог есть
  # или его нет. Форма `-c` для проверяющего узла закрывается ниже, как у `python3`.
  local vdir vname
  for vdir in ${PROFILE_AGENT_DIRS:-}; do
    for vname in .venv venv; do
      [[ -x "$vdir/$vname/bin/python" ]] || continue
      base+=",\"Bash($vdir/$vname/bin/python:*)\""
    done
  done

  rules="\"Bash(bash $FACTORY_HOME/lib/stage-result.sh:*)\",\"Bash($FACTORY_HOME/lib/stage-result.sh:*)\""
  rules+=",\"Bash(bash $FACTORY_HOME/lib/stage-progress.sh:*)\",\"Bash($FACTORY_HOME/lib/stage-progress.sh:*)\""
  # Опыт проверяющего узла: запуск кода без права изменить дерево (см. stage-probe.sh).
  # Выдаётся всем узлам, но нужен именно проверяющему — пишущему проще запустить напрямую.
  rules+=",\"Bash(bash $FACTORY_HOME/lib/stage-probe.sh:*)\",\"Bash($FACTORY_HOME/lib/stage-probe.sh:*)\""
  rules+=",$base$extra"
  # Запреты — второй рубеж после проверки диффа: команды автоформатирования не должны даже
  # запускаться. Профиль добавляет свои через PROFILE_AGENT_DENY.
  local deny='"Bash(npx eslint --fix:*)","Bash(eslint --fix:*)","Bash(npm run lint:fix:*)","Bash(yarn lint --fix:*)","Bash(pnpm lint --fix:*)","Bash(npx prettier --write:*)","Bash(prettier --write:*)"'
  if declare -p PROFILE_AGENT_DENY >/dev/null 2>&1; then
    local r
    for r in "${PROFILE_AGENT_DENY[@]}"; do deny+=",\"$r\""; done
  fi
  # Браузер — по явному разрешению узла маршрута (`policy.browser`), а не по
  # факту наличия MCP-сервера у CLI. Иначе разведка может менять данные живого
  # приложения песочницы, хотя этап должен только читать код.
  if [[ "${FACTORY_ROUTE_BROWSER_POLICY:-}" == forbid ]]; then
    deny+=',"mcp__playwright","mcp__playwright__*"'
  fi

  # ГЛАВНЫЙ рубеж для проверочных этапов: запрет ПИСАТЬ в каталоги проекта вообще.
  # Списка команд мало — он ловит «eslint --fix», но не «eslint . --fix» и не правку файла
  # редактором напрямую. Линт дважды (21.07 и 22.07) переформатировал 278-280 чужих файлов
  # в ветке задачи, хотя запрет в промпте стоял: просьба не работает, работает отсутствие прав.
  # Политикой файловой системы владеет закреплённый route bundle.
  if [[ -n "$stage" && "${FACTORY_ROUTE_FILESYSTEM_POLICY:-}" == state-only ]]; then
    # ЭТОТ запрет и есть та стена, ради которой узел объявлен state-only, — и до
    # 27.08.2026 он не работал вовсе: пути писались с одним слэшем, то есть считались
    # относительными проекту. Живой отказ: проверяющий узел инструментами Write и Edit
    # вернул env-файл песочницы к версии базовой ветки, снеся схемы задачи и адрес
    # Redis; поймал это только посмертный сторож, уже после работы узла.
    # Правило есть, но `Write(...)` CLI для файловых проверок не смотрит («only
    # Edit(path) rules are... Edit rules cover all file-editing tools»), поэтому
    # стену держит именно `Edit(...)`; остальные две формы оставлены как есть.
    local d tool_dir
    for d in ${PROFILE_AGENT_DIRS:-}; do
      [[ "$d" =~ ^/[A-Za-z0-9._/@%+=,:~-]+$ ]] || return 78
      tool_dir="//${d#/}"
      deny+=",\"Edit(${tool_dir})\",\"Edit(${tool_dir}/**)\""
      deny+=",\"Write(${tool_dir})\",\"Write(${tool_dir}/**)\""
      deny+=",\"NotebookEdit(${tool_dir})\",\"NotebookEdit(${tool_dir}/**)\""
    done
    # ЗАПРЕТА Edit/Write МАЛО: базовый allow выше открывает bash, а через bash файл
    # правится в обход прав на редактирование. LINT может переписать комментарий через
    # `sed -i`, затем унести файл задачи в `git stash`, раскидать файл по контейнерам
    # через `docker cp` и перемонтировать основной стенд.
    # Каждый раз сторож проверочных этапов валил этап и сбрасывал ВЕСЬ хвост от сборки
    # заново — по 40 минут на круг, и конвейер выглядел стоящим.
    #
    # Закрываем ходовые вектора. Стеной это не является и не может: `docker exec … pint`
    # (без --test) или `php -r` с записью правилами не выражаются — префиксная маска не
    # умеет заглядывать в середину команды. Настоящий рубеж — механический сторож
    # (_guard_readonly ниже), который сверяет список изменённых файлов до и после этапа.
    # Здесь мы лишь убираем то, за что агент хватается первым делом.
    deny+=',"Bash(sed -i:*)","Bash(perl -i:*)","Bash(tee:*)","Bash(truncate:*)","Bash(dd:*)"'
    deny+=',"Bash(cp:*)","Bash(mv:*)","Bash(rm:*)","Bash(docker cp:*)"'
    deny+=',"Bash(git checkout:*)","Bash(git restore:*)","Bash(git stash:*)","Bash(git reset:*)"'
    deny+=',"Bash(git clean:*)","Bash(git apply:*)","Bash(git rm:*)","Bash(git mv:*)"'
    deny+=',"Bash(git add:*)","Bash(git commit:*)"'
    # Инлайн-интерпретаторы: запуск СКРИПТА проверочному этапу нужен, однострочник с
    # записью — нет. Форма `-e/-r/-c` отсекается, `node script.mjs` остаётся рабочим.
    # Однострочник как ОПЫТ у узла теперь есть — `stage-probe.sh`: он выполняет тот же код,
    # но в одноразовом каталоге и со сверкой отпечатка деревьев до и после, поэтому запись
    # делает результат опыта недействительным сразу, а не через сорок минут.
    deny+=',"Bash(node -e:*)","Bash(php -r:*)","Bash(python3 -c:*)"'
    # Тот же запрет для питона проекта: разрешив venv выше, нельзя оставить в нём дыру,
    # которой нет у системного python3.
    for vdir in ${PROFILE_AGENT_DIRS:-}; do
      for vname in .venv venv; do
        [[ -x "$vdir/$vname/bin/python" ]] || continue
        deny+=",\"Bash($vdir/$vname/bin/python -c:*)\""
      done
    done
    # Обёртки, запускающие ЛЮБУЮ команду под своим именем. Правило сверяет ПРЕФИКС, поэтому
    # `timeout 60 sed -i …` не совпадает ни с одним запретом выше и проходит целиком. Хуже:
    # в личных настройках человека `Bash(timeout:*)` стоит в allow — то есть весь список
    # запретов обходится одним словом, и обходится молча. Запрещаем сами обёртки: этапу,
    # который только читает, они не нужны ни одной.
    deny+=',"Bash(timeout:*)","Bash(env:*)","Bash(xargs:*)","Bash(nohup:*)","Bash(setsid:*)"'
    deny+=',"Bash(stdbuf:*)","Bash(nice:*)","Bash(sudo:*)","Bash(sh -c:*)","Bash(bash -c:*)"'
    # Скрипты-обёртки package.json: что внутри — знает только сам package.json.
    # `npm run lint` фронта может оказаться объявлен как `eslint . --fix`, и автофикс перепишет
    # 276 чужих файлов, хотя флага --fix в команде агента не было и запрет на него стоял
    # и в промпте, и в deny. Проверочный этап зовёт линтер НАПРЯМУЮ (npx eslint --no-fix,
    # pint --test) — тогда команда видна целиком и правилами выражается. Прочие npm-скрипты
    # (сборка, e2e) не трогаем: режем только класс lint/format/fix.
    deny+=',"Bash(npm run lint)","Bash(npm run lint:*)","Bash(npm run format:*)","Bash(npm run fix:*)"'
    deny+=',"Bash(yarn lint:*)","Bash(pnpm lint:*)","Bash(npm exec eslint:*)"'
  fi

  # Permission syntax uses // for an absolute filesystem path. Deny both the
  # directory entry and every descendant: Read/Edit/Write/NotebookEdit are not
  # governed by Bash sandboxing and therefore need their own tool-level wall.
  # Пока sandbox снят (см. шапку функции), это единственная стена вокруг control root:
  # bash-командой каталог по-прежнему достижим, как было до ужесточения.
  [[ "$CONTROL_DIR" =~ ^/[A-Za-z0-9._/@%+=,:~-]+$ ]] || return 78
  tool_control="//${CONTROL_DIR#/}"
  deny+=",\"Read(${tool_control})\",\"Read(${tool_control}/**)\""
  deny+=",\"Edit(${tool_control})\",\"Edit(${tool_control}/**)\""
  deny+=",\"Write(${tool_control})\",\"Write(${tool_control}/**)\""
  deny+=",\"NotebookEdit(${tool_control})\",\"NotebookEdit(${tool_control}/**)\""

  # Превентивный рубеж проверяющего узла. Префиксное правило видит только НАЧАЛО команды,
  # поэтому запись через перенаправление им не выражается вовсе; хук получает команду
  # целиком до исполнения и отказывает по цели перенаправления. Ставится только на
  # `state-only`: пишущему узлу перенаправление законно.
  local hooks=""
  if [[ "${FACTORY_ROUTE_FILESYSTEM_POLICY:-}" == state-only ]]; then
    local guard="$FACTORY_HOME/lib/stage-write-guard.sh"
    # Оба пути уезжают внутрь JSON-строки и оттуда в командную строку хука. Проверяем их
    # тем же allowlist, что и control root выше: кавычка или обратный слэш сломали бы JSON
    # настроек молча, а пробел — разбор аргументов хука.
    if [[ -x "$guard" && "$guard" =~ ^/[A-Za-z0-9._/@%+=,:~-]+$
          && "$STATE_DIR" =~ ^/[A-Za-z0-9._/@%+=,:~-]+$ ]]; then
      local hook_cmd="$guard $STATE_DIR"
      hooks=',"hooks":{"PreToolUse":[{"matcher":"Bash","hooks":'
      hooks+="[{\"type\":\"command\",\"command\":\"$hook_cmd\"}]}]}"
    fi
  fi

  tmp=$(mktemp "$CONTROL_DIR/.agent-settings.XXXXXX") || return 1
  printf '{"permissions":{"allow":[%s],"deny":[%s]}%s}' \
    "$rules" "$deny" "$hooks" >"$tmp" || {
      rm -f -- "$tmp"
      return 1
    }
  chmod 400 -- "$tmp" || {
    rm -f -- "$tmp"
    return 1
  }
  mv -f -- "$tmp" "$f" || {
    rm -f -- "$tmp"
    return 1
  }
  echo "$f"
}

# --- лимит времени этапа ---
# Источник правды — КЛАСС узла из бандла маршрута (policy.timeoutClass), а не имя этапа:
# время диктует РОЛЬ узла (планирование, сборка, браузерная приёмка), и одна и та же схема
# должна вести себя одинаково у всех проектов. Дефолты ниже покрывают классы канонических
# маршрутов и намеренно повторяют прежние project-specific тайминги:
# смена источника правды не должна менять поведение работающих конвейеров.
_stage_timeout_class_default() {
  case "$1" in
    planning|standard|review|delivery|check) echo 1800 ;;
    test|build)                              echo 3600 ;;
    diagnostic|browser)                      echo 5400 ;;
    *)                                       echo ''   ;;
  esac
}

# $1=TASK $2=этап; echo секунды. Порядок: класс узла → хук профиля по классу → NODE_TIMEOUT.
_stage_timeout() {
  local t=${1:-} stage=${2:-} cls="${FACTORY_ROUTE_TIMEOUT_CLASS:-}" tmo="$NODE_TIMEOUT" v=""
  if [[ -n "$cls" ]]; then
    v=$(_stage_timeout_class_default "$cls")
    if [[ "$v" =~ ^[0-9]+$ ]]; then
      tmo="$v"
    else
      # Бандл объявил класс, которого движок не знает: молча взять дефолт — значит
      # дать узлу чужой лимит и потерять его работу по таймауту. Пишем в журнал.
      [[ -n "$t" ]] && flog "$t" "ЛИМИТ: неизвестный timeoutClass=$cls, беру $tmo с"
    fi
    # Проект вправе переопределить класс: у одного тесты идут пять минут, у другого час.
    if declare -F profile_timeout_class >/dev/null; then
      v=$(profile_timeout_class "$cls" 2>/dev/null)
      [[ "$v" =~ ^[0-9]+$ ]] && tmo="$v"
    fi
  fi
  printf '%s' "$tmo"
}

# --- черновик хода этапа ---
# Единственный терминальный канал — stage-result, и он срабатывает В КОНЦЕ. Между началом
# этапа и этим вызовом у движка нет ничего: убитый по таймауту агент уносит с собой всё, что
# успел понять. stage-progress сюда не годится — он маршрутный (ROUTE/SIZE/PLANS) и валидирует
# фиксированный список ключей, произвольную запись не принимает и принимать не должен.
# Поэтому черновик — обычный файл в STATE_DIR: агент уже имеет туда запись (см. _agent_settings),
# файл переживает и таймаут, и SIGKILL, и его же читает следующий заход.
# Имя детерминированное — по задаче и этапу: следующий заход должен НАЙТИ файл, не зная run_id.
_stage_checkpoint_path() {
  local t=$1 stage=${2:-any} lc
  lc=$(printf '%s' "${stage,,}" | tr -c 'a-z0-9_' '_')
  printf '%s/t%s.%s.checkpoint.md' "$STATE_DIR" "$t" "$lc"
}

_stage_checkpoint_clear() {
  local f; f=$(_stage_checkpoint_path "$1" "${2:-}")
  [[ -f "$f" && ! -L "$f" ]] && rm -f -- "$f"
  return 0
}

# Черновики живут внутри ПОПЫТКИ и снимаются при создании новой. Раньше их стирало каждое
# терминальное закрытие узла, и вопрос «а не примет ли заход чужие заметки за свои» решался
# сам собой — вместе с памятью между заходами (см. `_stage_checkpoint_seal`). Теперь граница
# проведена там, где ей место: заново запущенный прогон — это другая работа, его заметки не
# наследуются. Имя файла детерминированное, поэтому чистка — обычный glob по задаче; точка
# сразу за номером не даёт задаче с коротким номером задеть задачу с тем же префиксом.
_stage_checkpoint_clear_task() {
  local t=$1 f
  for f in "$STATE_DIR"/t"$t".*.checkpoint.md; do
    [[ -f "$f" && ! -L "$f" ]] && rm -f -- "$f"
  done
  return 0
}

# Закрытый узел черновик НЕ уносит, а подписывает. Удаление выглядело безопасным («иначе
# повторный заход на тот же узел через полгода примет чужие заметки за свои»), но ровно
# им оплачивался самый дорогой случай маршрута: узел закрывается `done`, критик его
# отклоняет, маршрут заходит сюда ВТОРОЙ раз — и получает промпт, побайтово равный
# первому. На повторном заходе первые чтения и вся разведка совпадают, расходуя контекст
# заново. Повтором движок это не считает
# (`_stage_retry_block` смотрит на FACTORY_STAGE_RETRY, а тут новая ЭПОХА узла), карта
# отвечает только на «где лежит», — значит единственный канал памяти между заходами
# один: черновик. Риск чужих заметок снимается подписью, а не стиранием: исход и время
# стоят в самом файле, и блок промпта показывает их заходу дословно.
_stage_checkpoint_seal() {
  local f outcome=${3:-done}
  f=$(_stage_checkpoint_path "$1" "${2:-}")
  [[ -s "$f" && ! -L "$f" ]] || return 0
  printf '\n---\nЗАХОД ЗАКРЫТ: исход `%s`, %s\n' \
    "$outcome" "$(date -u '+%Y-%m-%d %H:%M UTC')" >>"$f" 2>/dev/null
  return 0
}

# --- регламент времени в промпт ---
# Лимит знал только движок, агент работал вслепую и планировал проверки без оглядки на
# срок. Из-за этого он может уйти в необязательную регрессию, не успеть отчитаться и
# потерять вместе с этапом готовый код. Отдельного канала до агента нет, промпт
# нигде не хешируется, поэтому регламент приписывается служебным блоком в конец.
# Мягкий срок — 4/5 лимита: остаток нужен на саму фиксацию результата, она не мгновенная.
#
# Второй предел в том же блоке — раунды. Он не про время и не про деньги провайдера: заход
# из N раундов оплачивается квадратично (см. `_stage_task_map_block`), а выше ~250k контекста
# кэш промпта перестаёт совпадать и переписка пишется заново по двойному тарифу вместо
# чтения по десятой доле. Предел объявлен ПОРОГОМ СВЕДЕНИЯ, а не остановкой: молча брошенный
# заход движок считает «результата нет» и списывает попытку из бюджета этапа
# (`tries_left` в route-runtime), то есть остановка по счётчику отнимала бы автономию, ради
# которой всё и делается. Жёсткий вариант со своим счётчиком попыток — отдельная работа.
#
# Тут же — три правила счёта, сформулированные общими словами. Два про чтение:
# перечитанный собственный файл и служебные каталоги прогона (`wire.jsonl`). Третье
# про запись: артефакт этапа читают ВСЕ следующие узлы, поэтому раздутый `plan.md`
# многократно оплачивается на длинном маршруте, хотя сам документ
# размером в один файл. Правила стоят в движке, а не в промптах профилей: счёт одинаков для
# любого узла и любого проекта, а публикация каталога до старых попыток всё равно не доедет.
_stage_round_budget() {
  local n=${FACTORY_STAGE_ROUND_BUDGET:-}
  [[ "$n" =~ ^[1-9][0-9]*$ ]] || n=150
  printf '%s' "$n"
}

# Сроки названы и в минутах, и часами машины. Минуты «с начала этапа» агент отсчитать не
# может: своих часов у него нет, а модель не чувствует, сколько прошло между двумя
# вызовами инструментов. Живой замер (t7989, узел плана): три захода подряд по 30 минут,
# каждый убит перед самым stage-result — третий записал артефакт за 50 секунд до обрыва.
# Абсолютное время сверяется одной командой date, минуты — ничем.
# Третий аргумент — момент старта (epoch): тесты передают его явно, чтобы сверить часы
# в тексте с ожидаемыми; в бою — текущее время.
_stage_time_budget_block() {
  local tmo=$1 soft=$(( $1 * 4 / 5 )) ckpt=${2:-} started=${3:-} rounds
  local start_at soft_at hard_at

  rounds=$(_stage_round_budget)
  [[ "$started" =~ ^[0-9]+$ ]] || started=$(date +%s)
  start_at=$(date -d "@$started" +%H:%M)
  soft_at=$(date -d "@$(( started + soft ))" +%H:%M)
  hard_at=$(date -d "@$(( started + tmo ))" +%H:%M)
  cat <<EOF
---

## Регламент времени этапа (от движка, не от автора промпта)

Жёсткий предел — **$(( tmo / 60 )) мин**: старт в ${start_at}, обрыв в **${hard_at}** по
часам машины (своих часов у тебя нет — сверяйся командой \`date +%H:%M\`). По его
истечении процесс обрывается без предупреждения.

Всё, что не зафиксировано через \`stage-result\`, для движка не существует: этап
считается невыполненным и идёт заново. Следующему заходу достаются только файлы на
диске и черновик хода (ниже), а не твоя память.

Планируй так, чтобы результат был зафиксирован к **$(( soft / 60 )) мин** (${soft_at}).
Если к этому сроку главное сделано, а проверки нет — фиксируй сделанное и опиши остаток
в отчёте. После ${soft_at} новых линий разбора, ролей и поисков не открывай и проверку,
которая заведомо не уложится, не начинай: заход, убитый на последней команде, не стоит
ничего.

ЧЕРНОВИК ХОДА — \`${ckpt}\`. Дописывай туда строку каждый раз, когда закончил
осмысленный кусок: что сделано, где лежит, что проверено и что осталось. Это дёшево
(одна строка) и это единственное, что переживёт обрыв: файл достанется следующему
заходу дословно. Черновик ничего не завершает — этап закрывает только \`stage-result\`.

Второй предел — **раунды**, то есть твои обращения к модели. Модель не помнит предыдущее:
каждый следующий запрос заново оплачивает всё, что накопилось в заходе, поэтому сотня
раундов стоит не в сто раз дороже одного, а на порядки. Дорожает при этом не работа, а
поиск: несколько \`grep\`/\`ls\` подряд ради одного факта — самая дорогая часть захода при
самом маленьком результате.

Два чтения дороже всех прочих и не дают ничего. Первое — файл, который ты сам создал или
правил в этом заходе: что в нём написано, знаешь ты, а не диск, и перечитывание оплатит
его размер каждым оставшимся раундом. Второе — служебные каталоги прогона: журналы твоих
же вызовов (\`logs/runs/**\`), домашние каталоги раннера, состояние движка. Это не код
проекта и к задаче отношения не имеет.

Обратная сторона того же счёта — что ты пишешь в артефакт. Его читает каждый следующий
этап маршрута и с этого места везёт в каждом своём раунде: лишняя страница здесь стоит не
страницу, а сотню. Поэтому в артефакт идут решения, адреса (файл и символ) и проверки, а не
пересказ кода и не цитаты исходников — кому понадобится текст, откроет его по адресу.

Держись в **${rounds} вызовов инструментов** на заход. Подошёл к пределу — не начинай новую
линию разбора: сведи сделанное в черновик, доведи через \`stage-result\` то, что уже готово,
и назови остаток в отчёте. Бросить заход молча нельзя — движок считает такой заход
провалившимся и списывает попытку из бюджета этапа, «доделаю в следующий раз» здесь не
работает.
EOF
}

# --- правила записи проверяющего узла в промпт ---
# Права проверяющего узла (`_agent_settings`) закрывают копирование и перенос файлов
# целиком, а сторож записи (`stage-write-guard.sh`) пропускает перенаправление только в
# буквальный абсолютный путь каталога состояния или временного каталога. Самому агенту об
# этом не говорил никто: промпт называл лишь имя политики. Живой случай: узел перевода
# диагноза написал человеческую часть, а склеить её с исходным текстом пытался через `cp`,
# `tee` и относительный путь после `cd`, получил пять отказов, закрыл этап `failed` — и
# маршрут встал у человека, хотя `cat` в абсолютный путь был разрешён всё это время.
#
# Блок стоит в движке, а не в промптах профилей: правило одно для любого проверяющего узла,
# а публикация каталога до уже идущих попыток не доедет. Текст — в кавычечном heredoc (в нём
# markdown-обратные кавычки), каталог состояния и номер задачи подставляются по меткам.
_stage_filesystem_block() {
  local task=$1 text

  [[ "${FACTORY_ROUTE_FILESYSTEM_POLICY:-}" == state-only ]] || return 0
  text=$(cat <<'EOF'
---

## Запись файлов на проверяющем узле (от движка, не от автора промпта)

Рабочие деревья проекта узел только читает. Писать можно в каталог состояния
`@STATE_DIR@` (свои файлы — с префиксом `t@TASK@.`), а перенаправлением оболочки — ещё и в
`/tmp`. Путь всегда **буквальный абсолютный**: относительный путь, `~` и переменные сторож
записи не раскрывает, а `cd` не учитывает, поэтому `cd @STATE_DIR@ && cat > файл`
отклоняется как запись в дерево проекта.

- создать или поправить файл — инструментами записи и правки, по абсолютному пути внутри
  каталога состояния;
- копия — `cat <откуда> > @STATE_DIR@/<куда>`;
- склейка — `cat <первый> <второй> > @STATE_DIR@/<итог>`. Итог не должен быть среди
  источников: оболочка обнулит его раньше, чем `cat` прочитает. Поэтому файл, к которому
  дописываешь начало, сначала копируется, а склеивается уже из копии;
- код — опытом `stage-probe.sh` (см. выше) или файлом скрипта в каталоге состояния и
  запуском `python3 <путь>` / `node <путь>`;
- свой лишний файл не удаляй — оставь в каталоге состояния.

Отклоняются целиком, в том числе внутри длинной команды: `cp`, `mv`, `rm`, `tee`,
`sed -i`, `dd`, `truncate`, пишущие команды `git`, однострочники `python3 -c`, `node -e`,
`php -r` и обёртки `timeout`, `env`, `xargs`, `nohup`, `sh -c`, `bash -c`. Не трать на них
попытки.

Отказ прав — свойство среды, а не итог работы: не закрывай этап `failed`, пока не
попробовал способ отсюда. Нет такого способа — назови отказанную команду в причине.
EOF
)
  text=${text//@TASK@/$task}

  printf '%s\n' "${text//@STATE_DIR@/$STATE_DIR}"
}

# --- черновик предыдущего захода в промпт ---
# Файл достаётся заходу целиком, но с хвоста и с потолком: журнал на мегабайт вытеснит
# из окна само задание этапа, а ценен в нём именно конец — то, на чём заход оборвался.
_stage_checkpoint_block() {
  local f=$1 body
  # Байтовый tail может начать UTF-8 хвост с continuation-byte, если граница попала
  # внутрь многобайтного символа. Тогда один русский checkpoint отравляет весь prompt,
  # и provider отказывает ещё до model call. Python уже является зависимостью движка;
  # берём тот же ограниченный хвост и отбрасываем только неполные/битые последовательности.
  body=$(python3 - "$f" 2>/dev/null <<'PY'
import os
import sys

path = sys.argv[1]
try:
    size = os.path.getsize(path)
    with open(path, "rb") as source:
        source.seek(max(0, size - 6000))
        chunk = source.read(6000)
except OSError:
    raise SystemExit(1)

text = chunk.decode("utf-8", errors="ignore").replace("\0", "")
sys.stdout.buffer.write(text.encode("utf-8"))
PY
  ) || return 0
  [[ -n "$body" ]] || return 0
  # Два разных случая под одним файлом, и путать их нельзя: оборванный заход не дошёл до
  # результата, закрытый — дошёл, но его завернули дальше по маршруту. Второму заходу
  # важно знать, что перед ним не обломки, а сделанная работа, которую не приняли.
  local title='## Черновик незакрытого захода этого этапа' intro
  intro="Этап уже начинали, и он оборвался, не зафиксировав результат. Вот что успел записать
предыдущий заход (файл \`$f\`, последние строки):"
  if [[ "$body" == *'ЗАХОД ЗАКРЫТ:'* ]]; then
    title='## Заметки предыдущих заходов этого этапа'
    intro="Этап уже проходили, и заход дошёл до \`stage-result\` — строка «ЗАХОД ЗАКРЫТ» ниже
называет его исход. Ты здесь снова потому, что дальше по маршруту результат не приняли:
вернули критик, ворота или человек. Вот заметки, которые заходы вели сами
(файл \`$f\`, последние строки):"
  fi
  cat <<EOF
---

$title

$intro

\`\`\`
$body
\`\`\`

Это заметки, а не доказательство: сначала проверь, что описанное действительно на месте
(\`git status\`, \`git diff\`, файлы отчётов), и только потом продолжай с этого места.
Расхождение черновика с рабочим деревом — само по себе находка, назови её в отчёте.

Начинай именно отсюда. Всё, что здесь уже записано, заново выяснять не нужно: перечитывать
исходники ради фактов, стоящих в черновике, — самый дорогой способ узнать то, что ты уже
знаешь. Дописывай в тот же файл дальше, не стирая прежнее.
EOF
}

# --- карта задачи в промпт ---
# Раунд — это один запрос к модели, и модель не помнит предыдущий: заход из N раундов
# оплачивается примерно как N × (накопленный контекст) / 2, то есть КВАДРАТИЧНО по числу
# раундов. Проверенная выборка показала многократную переплату, причём значительная часть
# раундов уходила на повторный поиск того, что разведка уже нашла и записала в артефакт.
# Донести карту до остальных этапов может только
# движок: маршрут прибивается хешем при старте попытки, а промпты этапов принадлежат
# схеме и правятся по профилям — вклейка в них разъехалась бы на первой же формулировке.
# Способ тот же, что у черновика хода: служебный блок в конец промпта, одно место на все
# профили, все маршруты и все этапы.
_stage_task_map_path() {
  printf '%s/t%s.recon.md' "$STATE_DIR" "$1"
}

# Потолок 16 КБ (≈5k токенов) — втрое выше черновикового, и режется другой конец:
# у черновика ценен хвост (на чём оборвались), у карты — весь раздел целиком, поэтому
# отрезается её конец и об этом прямо сказано в тексте.
# Окупаемость: карта в K токенов на этапе из N раундов стоит K × N, а сэкономленный раунд
# возвращает средний контекст C — порог примерно K × N / C, то есть 6–8 раундов из тех
# полутора сотен, которые заход тратит на поиск.
_stage_task_map_block() {
  local f=$1 body
  # Разбор — python3 по тем же причинам, что и у черновика: обрезка байтами может попасть
  # внутрь многобайтного символа и отравить весь промпт до model call.
  body=$(python3 - "$f" 2>/dev/null <<'PY'
import re
import sys

LIMIT = 16000
# Заголовок карты задаёт промпт разведки. `Область изменения` — раздел, который recon.md
# содержал ДО введения карты: он даёт тот же список файлов, поэтому блок включается,
# не требуя ни одной правки в профилях и ни одной публикации каталога.
TITLES = ("карта задачи", "область изменения")

try:
    with open(sys.argv[1], "rb") as source:
        raw = source.read(1 << 20)
except OSError:
    raise SystemExit(1)

lines = raw.decode("utf-8", errors="ignore").replace("\0", "").splitlines()


def section(title):
    out, level, taking = [], 0, False
    for line in lines:
        head = re.match(r"^(#{1,6})\s+(.+?)\s*$", line)
        if head:
            depth = len(head.group(1))
            if taking:
                # Заголовок того же или более высокого уровня закрывает раздел,
                # более глубокий — часть карты и остаётся в теле.
                if depth <= level:
                    break
            elif head.group(2).strip().lower().rstrip(":").startswith(title):
                taking, level = True, depth
                continue
            else:
                continue
        if taking:
            out.append(line)
    return "\n".join(out).strip()


for name in TITLES:
    body = section(name)
    if body:
        break
else:
    raise SystemExit(1)

data = body.encode("utf-8")
if len(data) > LIMIT:
    body = data[:LIMIT].decode("utf-8", errors="ignore").rstrip()
    body += "\n\n(карта обрезана движком по потолку — остаток смотри в файле целиком)"
sys.stdout.buffer.write(body.encode("utf-8"))
PY
  ) || return 0
  [[ -n "$body" ]] || return 0
